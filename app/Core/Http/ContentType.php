<?php

declare(strict_types=1);

namespace Nabilet\Core\Http;

/**
 * Типы содержимого, которыми сайт обменивается — единственный владелец строк.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ КЛАСС. `'text/html; charset=utf-8'` был выписан в пяти
 * местах (`NotFoundPage`, `PageRenderer`, `LandingPageRenderer`,
 * `EventPageController` — дважды), `'application/json'` — в шести,
 * `'text/xml'` и `'text/csv'` — по разу. Литерал в пяти местах — это пять
 * точек правки, и расхождение здесь не падает: браузер угадывает кодировку,
 * и русский текст превращается в мусор не в тесте, а в чужом окне.
 *
 * Здесь же типы ИСХОДЯЩИХ запросов: `YooKassaProvider` объявляет JSON трижды,
 * `SendWebhookDeliveryJob` — один раз. Это то же самое правило, только про
 * тело, которое уходит наружу, а не отдаётся клиенту.
 *
 * ПРАВИЛО ПРО КОДИРОВКУ. Текстовые типы объявляют `charset=utf-8` явно.
 * Полагаться на то, что его допишет фреймворк, нельзя:
 * `Symfony\Response::prepare()` действительно добавляет `; charset=utf-8`
 * к любому `text/*`, но делает это ПРИ ОТПРАВКЕ — то есть заголовок,
 * прочитанный раньше (мидлвар, тест, лог), ещё без кодировки. Два типа из
 * этого класса (`XML`, `CSV`) на этот механизм до сих пор полагались; теперь
 * кодировка стоит в исходнике, и поведение не зависит от момента чтения.
 *
 * ИСКЛЮЧЕНИЯ, У КОТОРЫХ КОДИРОВКИ НЕТ НАМЕРЕННО:
 *   - `JSON` — UTF-8 предписан RFC 8259, а параметр `charset` для него
 *     бессмысленен и частью парсеров считается ошибкой;
 *   - `PDF` — двоичный формат, `charset` к нему неприменим.
 *
 * `text/xml`, а не `application/xml`: первое исторически ожидают краулеры
 * карт сайта (см. `SitemapController::xml()`), второе тоже принимается.
 */
final class ContentType
{
    /** HTML-страница. Кодировка обязательна: текст русский. */
    public const HTML = 'text/html; charset=utf-8';

    /** XML-документ (карты сайта). */
    public const XML = 'text/xml; charset=utf-8';

    /** Выгрузка CSV. */
    public const CSV = 'text/csv; charset=utf-8';

    /** JSON — кодировка задана спецификацией, параметр не нужен. */
    public const JSON = 'application/json';

    /** PDF-билет — двоичные данные. */
    public const PDF = 'application/pdf';
}
