<?php

declare(strict_types=1);

namespace Nabilet\Core\Support;

/**
 * Русские текстовые формы для серверных страниц (аудит P-12).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ КЛАСС. Посадочные страницы города и площадки собираются на
 * сервере и содержат числа («12 мероприятий в афише»), а также даты сеансов.
 * Витрина уже умеет и то и другое — `resources/js/lib/format.ts`, функции
 * `plural()` и `dateLong()`. Серверный дубль появился бы неизбежно, и разошёлся
 * бы он незаметно: «12 мероприятий» на посадочной и «12 мероприятие» в списке —
 * ровно тот машинный текст, который выдаёт непереведённый интерфейс.
 *
 * ОДНА РЕАЛИЗАЦИЯ НА ДВА ПОТРЕБИТЕЛЯ. Склонение вынесено сюда, а не в
 * `LandingPageService`, потому что его читает ещё и рендерер (заголовок,
 * вводный абзац, мета-описание строятся в разных местах). Формула — та же, что
 * в `plural()` витрины, и это осознанно: правила русских числительных одни и
 * те же, а расхождение здесь означало бы, что одна и та же цифра подписана
 * по-разному на двух экранах одного сайта.
 *
 * КЛАСС ЧИСТЫЙ: ни Laravel, ни I/O — только арифметика и `\DateTimeImmutable`
 * из стандартной библиотеки. Это требование purity-гейта к `app/Core/Support`
 * (каталог обязан грузиться без `vendor/`), и оно же делает класс пригодным для
 * тестов без базы и без фреймворка.
 *
 * ДВА ФОРМАТА ДАТЫ, И ЭТО НАМЕРЕННО
 *   `date()`/`dateTime()` дают «25 декабря» и «25 декабря, 19:00» — так дата
 *   читается в списке мероприятий. Но у сервера есть второй, узкий потребитель:
 *   письма, PDF-билет и блок «Дата и время» на странице события. Там нужна
 *   ОДНОЗНАЧНАЯ метка с годом, которую нельзя спутать и которая переживает
 *   копирование в чат поддержки, — «20.11.2026 19:30».
 *
 *   Раньше эта метка была выписана литералом в десяти местах, причём в трёх
 *   написаниях: `d.m.Y H:i` (семь), `d.m.Y` (одно), `d.m.Y, H:i` (одно) и
 *   `H:i` (два). Расхождение не косметическое: `FollowNotificationData`
 *   утверждал в комментарии, что отдаёт «ту же переменную и то же значение, что
 *   в заказных письмах», и это была правда ровно до первой правки одного из
 *   трёх мест. Формат `event_date` вообще закреплён тестом
 *   (`InventoryRepositoryContractTest`: «20.11.2026 19:30»), то есть менять его
 *   в одном месте, не меняя в других, нельзя было даже случайно.
 *
 *   Поэтому метка живёт здесь: `stamp()` — дата и время, `stampDate()` — только
 *   дата, `clock()` — только время. Все три принимают и `\DateTimeInterface`
 *   (модельные касты — это `Carbon`, он реализует тот же интерфейс), и строку
 *   из сырого запроса, и `null`.
 */
final class RuText
{
    /**
     * Родительный падеж месяцев — так дата читается в списке («25 декабря»),
     * тогда как «25 декабрь» выдаёт подстановку числа в именительный падеж.
     *
     * @var array<int, string>
     */
    private const MONTHS_GENITIVE = [
        1 => 'января',
        2 => 'февраля',
        3 => 'марта',
        4 => 'апреля',
        5 => 'мая',
        6 => 'июня',
        7 => 'июля',
        8 => 'августа',
        9 => 'сентября',
        10 => 'октября',
        11 => 'ноября',
        12 => 'декабря',
    ];

    /**
     * Компактная метка даты-времени — единственное место, где она записана.
     *
     * Значения — не «на вкус»: `d.m.Y H:i` закреплён тестом
     * (`InventoryRepositoryContractTest`), потому что попадает в переменную
     * `event_date` писем и в PDF-билет. Менять здесь — значит менять во всех
     * десяти потребителях сразу, и это ровно то, чего не было раньше.
     */
    private const STAMP = 'd.m.Y H:i';

    /** Только дата той же метки: «20.11.2026». */
    private const STAMP_DATE = 'd.m.Y';

    /** Только время: «19:30». */
    private const CLOCK = 'H:i';

    /**
     * Выбрать форму существительного по числу.
     *
     * Три формы, потому что в русском их три, и «5 билетов» отличается от
     * «2 билета» не окончанием строки, а другим словом. Выбор по последним двум
     * цифрам, а не по одной: 11–14 — исключение, которое склоняется как «11
     * билетов», хотя оканчивается на 1–4. Именно поэтому проверяется `% 100`.
     *
     * Отрицательные числа обрабатываются по модулю: «−3 билета» склоняется так
     * же, как «3 билета».
     */
    public static function plural(int $count, string $one, string $few, string $many): string
    {
        $mod10 = abs($count) % 10;
        $mod100 = abs($count) % 100;

        if ($mod10 === 1 && $mod100 !== 11) {
            return $one;
        }

        if ($mod10 >= 2 && $mod10 <= 4 && ($mod100 < 10 || $mod100 >= 20)) {
            return $few;
        }

        return $many;
    }

    /**
     * «25 декабря» — дата без года и времени.
     *
     * `null` и пустая строка возвращают `null`, а не подставленную дату: у
     * события может не быть сеанса, и «1 января 1970» здесь был бы выдумкой.
     * Неразбираемая строка возвращается как есть — это лучше, чем потерять
     * значение целиком из-за неожиданного формата.
     */
    public static function date(?string $iso): ?string
    {
        $moment = self::parse($iso);

        if ($moment === null) {
            return $iso === null || trim($iso) === '' ? null : trim($iso);
        }

        return $moment->format('j') . ' ' . self::MONTHS_GENITIVE[(int) $moment->format('n')];
    }

    /**
     * «25 декабря, 19:00» — дата и время сеанса.
     *
     * Время присутствует, потому что для билета оно существенно: два сеанса
     * одного события в один день различаются именно им, и «25 декабря» для них
     * выглядело бы как дубль в списке.
     */
    public static function dateTime(?string $iso): ?string
    {
        $moment = self::parse($iso);

        if ($moment === null) {
            return self::date($iso);
        }

        return self::date($iso) . ', ' . $moment->format(self::CLOCK);
    }

    /**
     * «20.11.2026 19:30» — компактная метка даты-времени.
     *
     * Зачем нужна вторая форма даты, когда есть `dateTime()`: см. докблок
     * класса. Коротко — однозначность. «25 декабря, 19:00» в письме о
     * неоплаченном заказе заставляет человека искать год, а в разговоре с
     * поддержкой даёт повод переспросить «это 2026-й?». Метка с годом такого
     * повода не даёт.
     *
     * `null` и пустая строка возвращают `null`, а не подставленную дату: у
     * заказа может не быть сеанса, а у розыгрыша — даты тиража, и «01.01.1970»
     * здесь был бы выдумкой. Неразбираемая строка тоже даёт `null` — вызывающий
     * решает, что показать вместо неё (чаще всего пустую строку или «дата не
     * записана»).
     */
    public static function stamp(\DateTimeInterface|string|null $moment): ?string
    {
        return self::moment($moment)?->format(self::STAMP);
    }

    /** «20.11.2026» — та же метка без времени. */
    public static function stampDate(\DateTimeInterface|string|null $moment): ?string
    {
        return self::moment($moment)?->format(self::STAMP_DATE);
    }

    /** «19:30» — только время: «места удержаны до 19:30». */
    public static function clock(\DateTimeInterface|string|null $moment): ?string
    {
        return self::moment($moment)?->format(self::CLOCK);
    }

    /**
     * Привести вход к `\DateTimeImmutable`.
     *
     * Две формы входа — не удобство ради удобства, а след реального кода:
     * модельные касты (`starts_at`, `drawn_at`) отдают `Carbon`, а
     * `UnpaidOrderReminderSweeper` и `AbandonedCartReminderSweeper` читают дату
     * сырым `DB::table()` и получают строку. Обе формы обязаны давать ОДИН
     * результат, иначе метка в письме зависела бы от того, как её прочитали.
     *
     * `createFromInterface`, а не `new \DateTimeImmutable($moment->format(...))`:
     * он сохраняет часовой пояс источника, поэтому дата не съезжает на сутки
     * при смене пояса приложения.
     */
    private static function moment(\DateTimeInterface|string|null $moment): ?\DateTimeImmutable
    {
        if ($moment instanceof \DateTimeInterface) {
            return \DateTimeImmutable::createFromInterface($moment);
        }

        return self::parse($moment);
    }

    /**
     * Разбор ISO-даты.
     *
     * `\DateTimeImmutable`, а не `Carbon`: Carbon живёт в `vendor/`, а этот
     * каталог обязан грузиться без него. Часовой пояс берётся из настроек PHP —
     * ровно тот же, в котором приложение формирует `starts_at`, поэтому
     * серверная дата совпадает с датой в базе.
     */
    private static function parse(?string $iso): ?\DateTimeImmutable
    {
        if ($iso === null || trim($iso) === '') {
            return null;
        }

        try {
            return new \DateTimeImmutable(trim($iso));
        } catch (\Exception) {
            return null;
        }
    }

    private function __construct()
    {
    }
}
