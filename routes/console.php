<?php

declare(strict_types=1);

use Illuminate\Support\Facades\Schedule;

/*
 * Closure commands and scheduled tasks live here.
 *
 * Two schedulers are required by the domain and are registered by their modules
 * in later phases, not here:
 *   - hold sweeper      — releases expired seat holds (ТЗ §24; срок берётся из
 *                         `seat_holds.expires_at`, а не из NABILET_HOLD_TTL —
 *                         см. пояснение в ClearExpiredHoldsCommand)
 *   - session expiry    — moves tickets to `expired` after a session ends
 *
 * Until then this stays empty; an artisan schedule that references missing jobs
 * fails the whole scheduler.
 */

// Очистка просроченных броней мест — запуск каждую минуту
// Требуется для шаред-хостинга где нет постоянных воркеров
// На Timeweb настроить в Crontab: * * * * * /opt/php83/bin/php /path/to/artisan schedule:run
// (именно php83: composer.json требует ^8.3 — см. аудит установщика W-4)
Schedule::command('seats:clear-expired')->everyMinute();

// Очередь: транзакционная почта и исходящие вебхуки кладутся в неё, чтобы
// сетевые вызовы не попадали в транзакцию оплаты. На шаред-хостинге нет
// постоянных воркеров, поэтому очередь разбирается порциями по крону:
// `--stop-when-empty` заставляет воркера выйти, как только она опустела, а
// `--max-time` гарантирует выход до следующей минуты.
//
// Lock снимается через 5 минут, а не через стандартные 24 часа: если воркер
// убьют, суточная блокировка остановила бы всю почту до ручного вмешательства.
Schedule::command('queue:work --stop-when-empty --max-time=50 --queue=default')
    ->everyMinute()
    ->withoutOverlapping(5);

// Повторы доставки вебхуков, у которых наступил next_retry_at. Ретрит не сама
// джоба, а эта команда: решение о повторе принимает RetryPolicy, который не
// повторяет 4xx — иначе мы превратились бы в источник нагрузки на чужой сервер.
Schedule::command('webhooks:retry-pending')->everyMinute();

// Напоминание покупателю за сутки до мероприятия: письмо с билетами, чтобы
// концерт не пропустили и QR-код был под рукой.
//
// РАЗ В ЧАС, а не раз в минуту. Свип берёт сеансы в окне [now + 24ч, now + 25ч),
// и шаг планировщика совпадает с шириной окна: каждый сеанс попадает ровно в
// один тик. Минутный запуск дал бы те же письма, но в 60 раз больше пустых
// выборок по `sessions.starts_at` — чистая нагрузка на БД без изменения
// результата.
//
// Идемпотентность — в OrderReminderSweeper (`order_reminders.order_id` UNIQUE),
// поэтому наложение двух тиков не удвоит письмо.
Schedule::command('orders:send-reminders')->hourly();

// Напоминание о незавершённой оплате: заказ «полежал» час — покупателю
// уходит письмо с суммой и ссылкой на оплату (одно письмо на заказ).
Schedule::command('orders:remind-unpaid')->hourly()->withoutOverlapping(15);

// Напоминание о брошенной корзине авторизованного покупателя: TTL корзины
// 15 минут, поэтому прогон раз в 5 минут — письмо приходит ДО истечения
// брони, пока места ещё живы. Гостевые корзины не напоминаются (контакта нет).
Schedule::command('carts:remind-abandoned')->everyFiveMinutes()->withoutOverlapping(4);

// Резервное копирование: ежедневный полный бэкап (дамп БД + storage/app/public)
// с выгрузкой на Яндекс.Диск (ТЗ §72).
//
// Раньше этой задачи не было ВООБЩЕ: `YandexDiskBackupService` существовал, но
// не вызывался ни одной командой и не был нигде в расписании. То есть «бэкапы
// есть» было утверждением без исполнителя — отказ диска означал безвозвратную
// потерю данных.
//
// 03:00 — вне пика продаж. `withoutOverlapping(120)`: дамп большой базы может
// идти дольше часа, и второй запуск поверх первого только испортил бы файл.
Schedule::command('backup:run')
    ->dailyAt('03:00')
    ->withoutOverlapping(120);

// Сверка зависших платежей с провайдером (аудит R-10).
//
// Вебхук — единственный штатный сигнал об оплате, а он может не дойти: сеть,
// недоступность нашего хоста, откат транзакции на 5xx. Тогда платёж навсегда
// остаётся `pending`, заказ — `awaiting_payment`, холд истекает, места
// перепродаются, а покупатель с оплаченным по данным банка заказом не получает
// ни билета, ни возврата. Эта команда — единственное, что такой случай замечает.
//
// 10 минут, а не минута: окно ожидания оплаты — 10 минут, поэтому опрос раньше
// смысла не имеет (платёж ещё легально `pending`), а чаще — это лишние запросы к
// ЮKassa по каждому живому платежу.
//
// `withoutOverlapping(9)`: проход делает сетевые вызовы и может идти дольше
// минуты; два параллельных прохода опрашивали бы одни и те же платежи дважды.
Schedule::command('payments:reconcile')->everyTenMinutes()->withoutOverlapping(9);

// Автоматическое завершение прошедших событий (SEO-аудит P-06).
//
// Статус `completed` ставился только вручную, поэтому прошедший концерт
// оставался `published` — а `published` в разметке означает «предстоит»:
// `eventStatus: EventScheduled` и `availability: InStock` для мероприятия,
// которое уже состоялось. Разметка, расходящаяся с реальностью, стоит доверия
// к ней целиком, а не только к одной странице.
//
// РАЗ В ЧАС, а не раз в минуту: событие становится прошедшим один раз в сутки, и
// минутный проход был бы 1440 пустыми выборками по `sessions.starts_at` в день.
// Часовая задержка перехода не видна ни пользователю, ни краулеру — Google
// переобходит страницу события не чаще, чем раз в несколько часов.
Schedule::command('events:sync-status')->hourly()->withoutOverlapping(30);

