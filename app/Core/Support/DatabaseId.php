<?php

declare(strict_types=1);

namespace Nabilet\Core\Support;

/**
 * «Это числовой идентификатор из базы?» — одно правило вместо четырёх копий.
 *
 * ЗАЧЕМ. Проверка `preg_match('/^\d{1,19}$/', $value) === 1` стояла в четырёх
 * местах, и два из них — побайтово одинаковые методы в двух контроллерах:
 *
 *   - `Checkin\Http\Controllers\Admin\CheckinDeviceController::find()`
 *   - `Checkin\Http\Controllers\Admin\OfflineBundleController::findDevice()`
 *   - `Checkin\Support\SessionLocator::resolve()`
 *   - `Checkin\Support\TicketLocator::publicIdOf()`
 *
 * (Первые два метода удалены вместе с их копиями запроса и копиями политики
 * 404 — см. `Core\Database\IdentifierLookup`.)
 *
 * Все четыре отвечают на один вопрос: клиент прислал внутренний `id` или внешний
 * `public_id`? Оба идентификатора приходят в одном и том же поле контракта
 * (`session_id: { type: string }`, `device_id`, `ticket_id`), потому что бандл
 * несёт public_id, а административный чекер исторически присылает число.
 *
 * ПОЧЕМУ ИМЕННО 19 ЦИФР, А НЕ 20. Это и есть правило, которое копировалось.
 * `sessions.id`, `tickets.id` и остальные первичные ключи — `BIGINT UNSIGNED`,
 * то есть до 18446744073709551615, ДВАДЦАТЬ цифр. Но `(int)` в PHP на 64-битной
 * платформе умеет до 9223372036854775807 — ДЕВЯТНАДЦАТЬ цифр. Строка из 20 цифр
 * приводится к int с молчаливым переполнением, и запрос уходит к ДРУГОЙ строке:
 * не ошибка, а чтение чужих данных. Девятнадцать — самая длинная длина, при
 * которой приведение точно не потеряет значение.
 *
 * ПОЧЕМУ НЕ `is_numeric()` И НЕ `intval()`. Оба принимают то, что id'ом не
 * является: `is_numeric('1e5')` и `is_numeric(' 12')` — true, а
 * `intval('012abc')` даёт 12. Вместо отказа запрос уходит к чужой записи. Регулярное
 * выражение требует, чтобы строка была ТОЛЬКО цифрами.
 *
 * Класс намеренно чистый: одна строковая операция, ни одного вызова фреймворка.
 * `app/Core/Support` обязан загружаться и работать без `vendor/` — это проверяет
 * `tools/verify-purity.php`, и импорт `Illuminate\...` здесь сломал бы гейт.
 *
 * @see docs/CODE-QUALITY-GUIDE.md — «Support»
 */
final class DatabaseId
{
    /**
     * Самая длинная десятичная запись, которую `(int)` представит точно.
     *
     * Девятнадцать, а не двадцать: 20-значный BIGINT UNSIGNED переполняет PHP int
     * на 64-битной платформе, и приведение молча отдаёт другое число.
     */
    public const MAX_DIGITS = 19;

    /**
     * Является ли строка десятичной записью внутреннего идентификатора.
     *
     * Fail-closed в сторону ОТКАЗА: всё, что не только цифры в пределах 19 штук,
     * здесь не id. Вызывающий тогда пробует public_id — и это правильно, потому
     * что поле контракта одно на оба идентификатора.
     */
    public static function isNumeric(mixed $value): bool
    {
        return is_string($value)
            && preg_match('/^\d{1,' . self::MAX_DIGITS . '}$/', $value) === 1;
    }

    /**
     * Внутренний id или null, если значение им не является.
     *
     * Null, а не 0: ноль — валидное значение для MySQL, но не валидное для
     * «билет не указан» (см. `TicketLocator`), и смешивать их нельзя.
     */
    public static function numericOrNull(mixed $value): ?int
    {
        return self::isNumeric($value) ? (int) $value : null;
    }
}
