const expanded = ref<string[]>(['launch'])

const filtered = computed(() => {
  const q = query.value.trim().toLocaleLowerCase('ru')
  if (!q) return SECTIONS
  return SECTIONS.filter((s) =>
    s.title.toLocaleLowerCase('ru').includes(q)
    || s.summary.toLocaleLowerCase('ru').includes(q)
    || s.items.some((line) => line.toLocaleLowerCase('ru').includes(q)),
  )
})

function toggle(id: string, open: boolean): void {
  if (open) expanded.value = [...new Set([...expanded.value, id])]
  else expanded.value = expanded.value.filter((x) => x !== id)
}

function expandAll(): void {
  expanded.value = filtered.value.map((s) => s.id)
}

function collapseAll(): void {
  expanded.value = []
}
