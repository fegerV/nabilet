 *
 *   Пока константы лежали в трёх файлах, они разъезжались ТРИЖДЕ. Последний раз:
 *   коммит `c581afbd` (лента новостей витрины) поднял счётчики до 88/911 в двух
 *   инструментах из трёх, и `verify-live.php` с тех пор падал на первой же
