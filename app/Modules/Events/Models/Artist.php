<?php

declare(strict_types=1);

namespace Nabilet\Modules\Events\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Support\Str;

/**
 * Артист — постоянная сущность каталога (стратегия SEO, B-1).
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ МОДЕЛЬ, А НЕ `event_artists`. `EventArtist` (пространство
 * `App\Models`) — это строка ПРОГРАММЫ внутри одного события: сцена, время
 * выхода, порядок. Одно и то же имя встречается там столько раз, сколько у
 * артиста событий, и в стольких написаниях, сколько раз его вводили руками.
 * Страница артиста — это ответ на вопрос «где и когда играет этот артист», и он
 * требует, чтобы все написания были одной записью. За это отвечает
 * `normalized_name` с UNIQUE-индексом в схеме.
 *
 * ГДЕ ЖИВЁТ МОДЕЛЬ. В модуле Events, рядом с `EventCategory`, — по той же
 * причине: категория тоже сущность КАТАЛОГА (без `organization_id`), и артист
 * устроен так же. Отдельный модуль `Artists` был бы честнее по границам, но
 * потянул бы `module.json`, провайдер и файл маршрутов ради одной модели, у
 * которой нет ни своих маршрутов, ни своей записи.
 *
 * КЛАСС НЕ ПИШЕТ. Единственный писатель — команда `artists:sync`, и она
 * НИКОГДА не перезаписывает поля существующей записи (подробности в докблоке
 * команды). Поэтому здесь нет ни мутаторов, ни скоупов записи: модель — это
 * чтение плюс две чистые функции нормализации, которыми пользуется синхронизация.
 */
class Artist extends Model
{
    protected $table = 'artists';

    protected $fillable = [
        'slug',
        'name',
        'normalized_name',
        'genre',
        'bio',
        'photo',
        'social_links',
        'seo_title',
        'seo_description',
        'status',
    ];

    protected $casts = [
        'social_links' => 'array',
    ];

    /**
     * События артиста — через связь `artist_event`, а не через `event_artists`.
     *
     * Имена внешних ключей не передаются: Laravel выводит их из имени модели
     * (`artist_id`) и имени связанной (`event_id`), и это ровно те колонки,
     * которые объявлены в схеме. Передать их строками значило бы завести вторую
     * копию того, что уже сказано конвенцией и совпадает с DDL.
     */
    public function events(): BelongsToMany
    {
        return $this->belongsToMany(Event::class, 'artist_event')
            ->withPivot(['is_headliner', 'sort_order'])
            ->withTimestamps();
    }

    /**
     * Ключ слияния написаний — то, что делает из «Би-2» и «БИ-2» одного артиста.
     *
     * ПРАВИЛО ПРОСТОЕ И ПРЕДСКАЗУЕМОЕ: нижний регистр, `ё` → `е`, всё, что не
     * буква и не цифра, — разделитель, повторные пробелы схлопываются. Так
     * «Би-2», «БИ-2», «„Би 2“» и «Би  2» дают одно значение `би 2`.
     *
     * ПОЧЕМУ НЕ `Str::slug()`. Slug транслитерирует и теряет различие, которого
     * здесь как раз не должно быть, но он же и склеивает то, что склеивать
     * нельзя: `Str::slug('Би-2')` и `Str::slug('Би 2')` совпадают, а `slug`
     * обязан остаться уникальным и СТАБИЛЬНЫМ адресом. Поэтому ключ слияния и
     * адрес — разные вещи: ключ решает, «тот же это артист или нет», адрес
     * выбирается один раз при создании и больше не меняется.
     *
     * ПЕРЕОБЪЕДИНЕНИЕ ВОЗМОЖНО, И ЭТО ОСОЗНАННЫЙ РИСК. Слишком агрессивная
     * нормализация склеит двух разных артистов в одну страницу, и разлепить их
     * потом придётся руками. Именно поэтому команда синхронизации умеет
     * `--dry-run`: список слияний показывается ДО записи, а не после.
     */
    public static function normalizeName(string $name): string
    {
        $lower = Str::lower(trim($name));
        $lower = str_replace('ё', 'е', $lower);

        $spaced = preg_replace('/[^\p{L}\p{N}]+/u', ' ', $lower) ?? $lower;
        $collapsed = preg_replace('/\s+/u', ' ', $spaced) ?? $spaced;

        return trim($collapsed);
    }

    /**
     * Адрес страницы артиста из его имени.
     *
     * `Str::slug()` транслитерирует неинтуитивно (`Тюмень` → `tiumen`), поэтому
     * адрес — публичный контракт: в тестах он пишется явно, а не вычисляется
     * этим же вызовом. Иначе тест повторил бы ошибку библиотеки и ничего не
     * поймал бы.
     *
     * Пустой результат возможен (имя из одних символов, которые не
     * транслитерируются) — тогда возвращается `artist`, а уникальность
     * обеспечивает вызывающий: суффикс добавляется там, где видно занятые
     * адреса.
     */
    public static function slugFor(string $name): string
    {
        $slug = Str::slug($name);

        return $slug === '' ? 'artist' : $slug;
    }
}
