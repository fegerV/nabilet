<?php

declare(strict_types=1);

namespace Nabilet\Core\Support;

/**
 * Байты, которые уходят в HMAC.
 *
 * ЗАЧЕМ. Подпись считается не над массивом, а над строкой, и подписывающая с
 * проверяющей стороной обязаны получить ОДИН И ТОТ ЖЕ текст. Набор флагов
 * `json_encode` при этом был выписан в четырёх местах:
 *
 *   - `Payments\Services\WebhookSignatureVerifier::body()` — запасной путь,
 *     когда сырое тело не передали
 *   - `Payments\Providers\YooKassaProvider::verifySignature()`
 *   - `Tickets\Services\TicketService::generateQrCode()`
 *   - `Webhooks\Jobs\SendWebhookDeliveryJob` — подпись исходящего тела
 *
 * Причём `TicketService` писал их в ДРУГОМ ПОРЯДКЕ (`SLASHES | UNICODE`), чем
 * остальные три. Поведение от порядка не меняется — и именно поэтому это
 * доказательство, что флаги копировали руками, а не брали у владельца: тот, кто
 * копирует, порядок не сохраняет.
 *
 * ОПАСНОСТЬ НЕ В ФОРМАТЕ, А В РАСХОЖДЕНИИ. Флаги влияют на байты: без
 * `JSON_UNESCAPED_UNICODE` кириллица превращается в `\u0410…`, без
 * `JSON_UNESCAPED_SLASHES` — `/` в `\/`. Обе стороны одного протокола
 * (`X-Nabilet-Signature`: мы подписываем, подписчик проверяет) должны
 * сериализовать одинаково, иначе подпись честного отправителя не сходится.
 * Хуже: если разойдутся НАШИ подписывающая и проверяющая стороны, тест не
 * заметит — он тоже наш и повторит ошибку.
 *
 * ПОЧЕМУ НЕ `JSON_THROW_ON_ERROR`. Политика отказа у вызывающих разная: джоба
 * завершает доставку с ошибкой, сервис платежей возвращает `false`, выпуск
 * билета бросает исключение. Общий владелец, который бросает, навязал бы одну
 * политику четырём разным контекстам. Поэтому здесь `null`, а решение — у
 * вызывающего.
 *
 * ПОЧЕМУ НЕ `JSON_PRETTY_PRINT`. Подпись — над компактным текстом; пробелы и
 * переводы строк в подписанных байтах только увеличивают объём и добавляют
 * ещё один параметр, который стороны должны согласовать.
 *
 * Класс чистый: `json_encode` — встроенная функция PHP.
 *
 * @see HmacSignature — что с этими байтами делают дальше
 */
final class SignedPayload
{
    /**
     * Набор флагов, под которыми байты попадают в HMAC.
     *
     * Приватная: снаружи есть только `encode()`. Публичная константа позволила
     * бы снова писать `json_encode($payload, SignedPayload::FLAGS)` в обход
     * владельца — и вернула бы ровно ту копию, которую убрали.
     */
    private const FLAGS = JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES;

    /**
     * Сериализовать полезную нагрузку для подписи.
     *
     * `null` — сериализовать не удалось (ресурс, рекурсия, битая UTF-8).
     * Пустая строка — валидный результат: подписывать `""` можно, и запрещать
     * это здесь значило бы решать за вызывающего.
     */
    public static function encode(mixed $payload): ?string
    {
        $json = json_encode($payload, self::FLAGS);

        return is_string($json) ? $json : null;
    }
}
