<?php

declare(strict_types=1);

namespace Nabilet\Modules\System\Console;

use Illuminate\Console\Command;
use Nabilet\Modules\System\Support\ProductionSafetyAudit;

/**
 * Проверка конфигурации на безопасность для продакшена (ТЗ §79, P0-7).
 *
 * ЗАЧЕМ КОМАНДА, ЕСЛИ ЕСТЬ `ProductionSafetyProvider`
 * ------------------------------------------------
 * Провайдер срабатывает в одном случае: `boot()` при `APP_ENV=production`. Он
 * закрывает главный сценарий — «скопировали `.env.example`, приложение не
 * поднялось» — но у него есть слепое пятно, и оно дорогое: на стенде, где
 * `APP_ENV` ещё не `production`, он молчит. То есть небезопасная конфигурация
 * обнаруживается не до деплоя, а в момент переключения трафика, когда
 * приложение отказывается стартовать.
 *
 * Эта команда вызывает ТЕ ЖЕ правила (см. `ProductionSafetyAudit` — правила
 * живут там в одном экземпляре) явно и заранее:
 *
 *     php artisan config:validate && <деплой>
 *
 * Ненулевой код возврата делает её пригодной для скрипта деплоя и для CI, где
 * проверка запускается на `.env`, собранном из шаблона.
 *
 * ПОЧЕМУ ОНА НЕ СМОТРИТ НА `APP_ENV`
 * ---------------------------------
 * Соблазн «проверять только в продакшене» вернул бы то же слепое пятно, ради
 * закрытия которого команда и написана: гейт, который на стенде ничего не
 * проверяет, — не гейт. Поэтому правила применяются всегда, а окружение
 * печатается в вывод: локальный запуск на dev-конфигурации честно падает
 * (`APP_DEBUG=true`, `PAYMENT_DEMO_MODE=true`) — это ответ на вопрос «годится ли
 * эта конфигурация для продакшена», а не на вопрос «правильная ли она сейчас».
 */
final class ConfigValidateCommand extends Command
{
    /** @var string */
    protected $signature = 'config:validate';

    /** @var string */
    protected $description = 'Проверить конфигурацию на безопасность для продакшена (ТЗ §79)';

    public function handle(ProductionSafetyAudit $audit): int
    {
        $violations = $audit->violations();

        if ($violations === []) {
            $this->info('Конфигурация безопасна для продакшена.');

            return self::SUCCESS;
        }

        $this->error(sprintf(
            'Небезопасная конфигурация: %d нарушение(й). Приложение с такой конфигурацией '
            . 'не поднимется при APP_ENV=production — это намеренно (fail-closed).',
            count($violations)
        ));

        foreach ($violations as $violation) {
            $this->line('  - ' . $violation);
        }

        // Окружение печатается всегда, потому что оно объясняет результат:
        // на dev-конфигурации нарушения ожидаемы и означают «в продакшен так
        // нельзя», а не «сейчас что-то сломано».
        $this->newLine();
        $this->line(sprintf(
            'APP_ENV=%s. Правила описывают требования к продакшену; локальная разработка '
            . 'может законно им не соответствовать.',
            (string) config('app.env')
        ));

        return self::FAILURE;
    }
}
