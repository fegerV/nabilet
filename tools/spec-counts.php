 *   (OpenAPI против DDL). Каждый парсит `nabilet_core_spec/migrations.sql` своим
 *   парсером и сверяет результат с ожиданием — так ловится парсер, который
 *   недосчитал: недосчитавший парсер не «падает», он изобретает дрейф, а
