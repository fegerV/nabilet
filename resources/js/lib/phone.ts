/**
 * Единственный владелец правила валидации телефона покупателя.
 *
 * Раньше правило «ровно 11 цифр» было вписано двумя буквально одинаковыми
 * строками — в `pages/storefront/CheckoutPage.vue` и в
 * `pages/storefront/usePurchaseFlow.ts`. Копии компилируются, поэтому и не
 * выглядят ошибкой, но разойдутся при первой же правке: кто-то поправит
 * сообщение в одной форме и забудет про вторую, или поменяет условие (например,
 * «начиная с 7» перестанет быть только словом в тексте и станет проверкой).
 * Поэтому правило вынесено сюда и ВЫЗЫВАЕТСЯ, а не копируется. Статический
 * сторож в `tests/Unit/phone.test.ts` не даёт появиться второй копии.
 */

/**
 * Сообщение об ошибке, если в строке телефона не ровно 11 цифр; иначе `null`.
 *
 * Небуквенные символы (пробелы, скобки, «+», дефисы) отбрасываются перед
 * подсчётом — `+7 912 345-67-89` и `79123456789` равноправны. Длина сверяется
 * ровно с 11: это российский мобильный номер целиком.
 */
export function phoneError(phone: string): string | null {
  return phone.replace(/\D/g, '').length !== 11
    ? 'Телефон — 11 цифр, начиная с 7'
    : null
}
