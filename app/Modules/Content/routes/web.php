<?php

declare(strict_types=1);

use Illuminate\Support\Facades\Route;
use Nabilet\Modules\Content\Http\Controllers\PageController;

/*
 * Web-маршруты модуля Content — редакционные страницы CMS (стратегия SEO, B-2).
 *
 * ПОЧЕМУ В WEB, А НЕ В API. Те же причины, что у посадочных страниц модуля
 * Seo: это человекочитаемые адреса, которые открывают из поиска, и они
 * обязаны отвечать HTML-документом. Адрес с `/api/v1/` в выдаче —
 * технический префикс там, где должен быть смысл.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ В КОРНЕВОМ `routes/web.php`. Правило проекта:
 * маршрут принадлежит модулю, который его обслуживает
 * (`tools/verify-route-ownership.php`). `routes/web.php` — единственный
 * владелец подключения, но не автор маршрутов.
 *
 * ПОРЯДОК РЕГИСТРАЦИИ. Подключается ВЫШЕ `Route::fallback()` в корневом
 * `routes/web.php`, иначе брендированная 404 перехватывала бы запрос: маршрут,
 * объявленный после `fallback()`, не получит запрос никогда.
 *
 * ПРЕФИКС `/page/`, А НЕ КОРОТКИЙ `/{slug}`. Маршрут из одного сегмента в корне
 * — это маска, перехватывающая ЛЮБОЙ односегментный путь. Сегодня она ничего
 * не ломает, но она гарантированно проглотит первый же будущий маршрут вида
 * `/about` или `/help` — точно так же, как проект уже платил за маску `{any}`
 * против `/api/v1` (см. комментарий к `Route::fallback()`). Префикс `/page/`
 * ровно описывает адресное пространство редакционных страниц.
 *
 * ИМЯ МАРШРУТА `content.page`. Адрес строится в одном месте (`route('content.page', …)`),
 * и переименование здесь потребует ровно одну правку в `SitemapService` и
 * `PageDocument::canonical()`. Расхождение этих трёх вызовов молча уронило
 * бы sitemap 500-кой.
 */
Route::get('/page/{slug}', [PageController::class, 'show'])->name('content.page');