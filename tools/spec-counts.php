/** Таблиц в бандле спеки. Сверяется с `spec_ddl_tables()` при каждом прогоне. */
const EXPECTED_TABLES = 88;

/** Колонок в бандле спеки (CREATE TABLE + ALTER TABLE ADD COLUMN). */
const EXPECTED_COLUMNS = 953;

/**
 * Сколько `CREATE TABLE` в бандле — независимая от парсеров величина.
 *
 * Шаблон повторяет форму объявлений в бандле (`CREATE TABLE IF NOT EXISTS \`x\` (`)
 * и намеренно не считает упоминания в комментариях: там нет открывающей скобки.
 */
function spec_ddl_tables(string $specSql): int
{
    return preg_match_all('/CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?`?\w+`?\s*\(/i', $specSql) ?: 0;
}

/**
 * Сверить константу с самой спекой. Возвращает текст ошибки или `null`.
 *
 * Вызывается из каждого инструмента ДО того, как он начнёт сравнивать свой
 * разбор с ожиданием: иначе отставшая константа выглядит как сломанный парсер.
 */
function spec_counts_problem(string $specSql): ?string
{
    $ddl = spec_ddl_tables($specSql);

    if ($ddl === EXPECTED_TABLES) {
        return null;
    }

    return sprintf(
        "spec-counts.php отстал от спеки: в бандле %d CREATE TABLE, в константе EXPECTED_TABLES = %d.\n"
        . "        Обновите tools/spec-counts.php — его читают все три инструмента.",
        $ddl,
        EXPECTED_TABLES
    );
}
