<?php

declare(strict_types=1);

namespace Nabilet\Core\Idempotency;

/**
 * Имя заголовка идемпотентности — ОДИН владелец контрактной строки.
 *
 * `Idempotency-Key` объявлен в `docs/openapi.yaml` и читается в четырёх местах:
 * мидлваром `EnsureIdempotency` (сам механизм), контроллером встраиваемого
 * виджета (`EmbedController`), фолбэком платежей (`PaymentController`) и списком
 * разрешённых CORS-заголовков (`CorsHeaders`). Пока имя было выписано в каждом
 * по отдельности, переименование в контракте оставило бы одну из копий на старом
 * имени — и мидлвар читал бы не тот заголовок, что шлёт клиент: идемпотентность
 * молча переставала бы работать, а повторный платёж проходил бы дважды.
 *
 * Класс намеренно чистый (ни одного импорта фреймворка): это просто строка
 * контракта, и она не должна тянуть за собой HTTP-слой.
 */
final class IdempotencyHeader
{
    /** Каноничное имя заголовка из контракта. */
    public const NAME = 'Idempotency-Key';
}
