<?php

declare(strict_types=1);

namespace Nabilet\Core\Support;

/**
 * Публикационный статус сущности каталога — одно правило на пять колонок.
 *
 * ЧТО БЫЛО. Пять таблиц объявляют колонку почти побайтово одинаково:
 *
 *   organizations     status VARCHAR(32) NOT NULL DEFAULT 'active'
 *   event_categories  status VARCHAR(32) NOT NULL DEFAULT 'active'
 *   venues            status VARCHAR(32) NOT NULL DEFAULT 'active'
 *   halls             status VARCHAR(32) NOT NULL DEFAULT 'active'
 *   artists           status VARCHAR(32) NOT NULL DEFAULT 'active'
 *
 * (канон — `nabilet_core_spec/migrations.sql`, строки 18, 126, 207, 231, 1749).
 * Словарь у всех начинается с `active` / `inactive`, — и правило «что значит
 * каждое слово» было выписано в коде семнадцать раз: три раза готовой строкой
 * `in:active,inactive` в правилах валидации, четыре раза значением по умолчанию
 * при создании, десять раз литералом в фильтрах выборки. Ни одной связи между
 * этими семнадцатью записями не было.
 *
 * ОГОВОРКА ПРО `organizations`, КОТОРУЮ НЕЛЬЗЯ ПРОПУСТИТЬ. У этой колонки
 * словарь ШИРЕ: `active | inactive | suspended`, и это не догадка —
 * `2026_10_12_000500_add_status_vocabularies.php` ставит на неё
 * `ck_organizations_status` ровно с тремя значениями, а
 * `UpdateOrganizationRequest` валидирует `in:active,inactive,suspended`. Поэтому
 * `all()` и `validationRule()` ниже — БАЗОВЫЙ словарь, то есть тот минимум,
 * который совпадает у всех пяти колонок; применять `validationRule()` к
 * организации нельзя, иначе `suspended` перестанет приниматься. Для организации
 * здесь берётся только `publiclyVisible()` — вопрос «видно ли её в каталоге» у
 * всех пяти колонок имеет один ответ, даже когда список допустимых значений
 * разный. Это разные вопросы, и путать их — значит либо запретить `suspended`,
 * либо начать показывать приостановленных.
 *
 * ПОЧЕМУ ЭТО НЕ КОСМЕТИКА. Литерал в фильтре — это не украшение запроса, а
 * решение «показывать или нет». Переименуй значение (`active` → `published`),
 * поправь правила валидации — и каждая выборка продолжит искать слово, которого
 * больше нет. Симптом при этом не выглядит как ошибка:
 *
 *   • витрина отвечает 200 и отдаёт пустой список городов;
 *   • `sitemap-venues.xml` отдаёт корректный XML без единого адреса;
 *   • страницы площадок, артистов, организаторов и категорий отвечают 404.
 *
 * Ни одного исключения, ни одной строки в логе. Именно поэтому это дефект, а не
 * стиль: цена расхождения — молча опустевший каталог, а не пятисотка.
 *
 * ГДЕ ВИДНО, ЧТО ЭТО ОДНО ПРАВИЛО, А НЕ ПЯТЬ. В `CatalogService` четыре метода
 * подряд — `venueBySlug()`, `categoryBySlug()`, `organizationBySlug()`,
 * `artistBySlug()` — устроены одинаково и заканчивались одной строкой
 * `->where('status', 'active')`. Четыре копии в одном файле, между которыми
 * отличается только имя модели. Разделять их по модулям можно было бы, но тогда
 * пришлось бы объяснить, чем публикация артиста отличается от публикации
 * площадки, — а она не отличается ничем: и то и другое скрывает сущность из
 * каталога и закрывает её адрес.
 *
 * ПОЧЕМУ КЛАСС, А НЕ МАШИНА СОСТОЯНИЙ. У `events.status` и `pages.status` есть
 * настоящие машины состояний (`EventStateMachine`, `PageStatus`), потому что там
 * статус ПЕРЕХОДИТ: черновик → на модерации → опубликован → отменён, с
 * проверками допустимости перехода и историей. У этих пяти колонок переходов
 * нет вовсе: значение меняется прямым редактированием в админке, промежуточных
 * состояний не существует, и «отменить публикацию» — это не переход, а
 * присваивание. Машина состояний из одного ребра была бы обёрткой без предмета.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. CHECK-ограничения на четырёх из пяти колонок в схеме нет —
 * это записано в самой миграции словарей (`add_status_vocabularies.php`,
 * раздел «ЧТО ОСТАЁТСЯ СВОБОДНЫМ»: `venues.status`, `halls.status`,
 * `event_categories.status` там перечислены явно, `artists.status` не покрыт
 * ничем). Значит запись мимо HTTP — сидер, скрипт, будущий эндпоинт — по-прежнему
 * может положить в колонку что угодно, и ни один фильтр этого не заметит:
 * `WHERE status = 'active'` на строке `'activ'` даёт пустоту, а не ошибку.
 * Класс закрывает расхождение КОДА, а не базы. Ограничение — отдельная работа
 * по миграции, и её отсутствие записано здесь, чтобы не выглядело забытым.
 *
 * Пятая колонка — `organizations.status` — уже под CHECK, и это единственная из
 * пяти, у которой мусор в колонке падает громко. Полагаться на это нельзя:
 * поведение класса не должно зависеть от того, какой из пяти колонок повезло.
 *
 * ЧЕГО ЭТОТ КЛАСС НЕ ОБСЛУЖИВАЕТ — И ЭТО ВАЖНО. Колонки с именем `active` в
 * `embed_domains`, `redirects`, `notification_templates` — булевы, а не
 * статусы; у `checkin_devices`, `carts`, `users`, `promo_codes`, `raffles` свои
 * словари со своими владельцами. Совпадение слова `active` не делает правило
 * общим: у устройства на контроле `active` значит «разрешено сканировать
 * билеты», а не «видно в каталоге»; у места в зале (`seats.status`,
 * `ck_seats_status`: `active|blocked|disabled`) — «место продаётся», а не
 * «площадка опубликована». Поэтому владелец у каждого свой, и объединять их
 * нельзя.
 *
 * Класс намеренно чистый (без illuminate): `app/Core/Support` обязан
 * загружаться без `vendor/`, это проверяет `tools/verify-purity.php`.
 */
final class PublicationStatus
{
    public const ACTIVE = 'active';
    public const INACTIVE = 'inactive';

    /**
     * Базовый словарь — тот минимум, который принимают все пять колонок.
     *
     * Не «полный список допустимых значений»: `organizations.status` шире на
     * `suspended`. См. оговорку в докблоке класса.
     *
     * @return list<string>
     */
    public static function all(): array
    {
        return [self::ACTIVE, self::INACTIVE];
    }

    /**
     * Готовое правило Laravel для поля `status`: `in:active,inactive`.
     *
     * ТОЛЬКО ДЛЯ КОЛОНОК, ЧЕЙ СЛОВАРЬ РАВЕН БАЗОВОМУ. Сейчас таких две:
     * `venues.status` и `halls.status`. Для `organizations.status` это правило
     * неверно — оно отсекло бы `suspended` (см. оговорку в докблоке класса);
     * там своё правило, в `UpdateOrganizationRequest`.
     */
    public static function validationRule(): string
    {
        return 'in:' . implode(',', self::all());
    }

    /**
     * Статусы, которые каталог считает видимыми.
     *
     * Отдельный метод, а не сравнение с `self::ACTIVE` в вызывающем: список
     * может расшириться (например, `temporarily_closed` для площадки, которая
     * закрыта на ремонт, но остаётся в выдаче), и тогда правка будет здесь, а не
     * в десяти запросах каталога.
     *
     * @return list<string>
     */
    public static function publiclyVisible(): array
    {
        return [self::ACTIVE];
    }

    public static function isPubliclyVisible(string $status): bool
    {
        return in_array($status, self::publiclyVisible(), true);
    }

    /** Prevent instantiation. */
    private function __construct()
    {
    }
}
