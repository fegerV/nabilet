<?php

declare(strict_types=1);

namespace Nabilet\Modules\Loyalty\Domain;

use DateTimeImmutable;
use Nabilet\Core\Errors\DomainRuleViolation;
use Nabilet\Core\Support\Money;

/**
 * Правила бонусного счёта: сколько начислить, сколько можно списать, когда сгорает.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ ОБЪЕКТ, А НЕ КОНСТАНТЫ В СЕРВИСЕ
 *   Числа здесь — продуктовые решения (таблица «Правила бонусов» в
 *   `docs/LOYALTY-PLAN.md`), а не детали реализации одного вызывающего. Если бы
 *   5% жили в `BonusService`, а 30% — в чекауте, то изменение ставки требовало
 *   бы найти все места, где она упомянута, и любое пропущенное дало бы две
 *   разные ставки в одной системе. Здесь ставка одна, и она проверяема без
 *   базы: класс не знает ни Laravel, ни I/O (см. `tools/verify-purity.php`).
 *
 * ЕДИНИЦЫ
 *   Все суммы — `Money`, то есть целые минорные единицы. Курс отображения
 *   («1 бонус = 1 ₽», `MINOR_UNITS_PER_BONUS = 100`) живёт здесь же, потому что
 *   он часть правила, а не оформления: витрина и API обязаны делить на одно и
 *   то же число, иначе баланс на экране и в письме разойдутся в 100 раз.
 *
 * ЧТО ИМЕННО СЕЙЧАС ИСПОЛЬЗУЕТСЯ
 *   Фаза 2a использует только `accrualFor()`. `maxSpendable()` и `expiresAt()` —
 *   правила фаз 2b и свипа срока; они объявлены здесь, потому что это те же
 *   продуктовые решения и потому что списание, реализованное без лимита, — это
 *   дыра в деньгах, а не «недоделанная фича».
 */
final class BonusPolicy
{
    /** Начисление: 5% от итога к оплате (`orders.total_amount`). */
    public const ACCRUAL_PERCENT = 5.0;

    /** Лимит списания: не больше 30% от subtotal заказа. */
    public const SPEND_CAP_PERCENT = 30.0;

    /** Срок жизни начисленных бонусов. */
    public const LIFETIME_MONTHS = 12;

    /**
     * Курс отображения: 1 бонус = 1 ₽, то есть 100 минорных единиц.
     *
     * В базе бонусы лежат в минорных единицах (иначе `orders.bonus_amount`
     * нельзя поставить в один CHECK с `subtotal_amount`/`total_amount`), а
     * покупателю показываются «бонусами». Делит их представление — этот
     * коэффициент, и только он.
     */
    public const MINOR_UNITS_PER_BONUS = 100;

    /**
     * Кэшбэк за оплаченный заказ.
     *
     * `total_amount`, а не `subtotal_amount`: покупатель платит итог, и кэшбэк
     * «от суммы покупки» на языке покупателя — это то, что он заплатил.
     * Округление — половина вверх (`Money::percentage`): 5% от 12 345 минорных
     * единиц — это 617, а не 617,25 и не 617,2.
     *
     * Нулевой заказ возвращает ноль: движения на ноль в журнале не должно быть,
     * иначе история покупателя забьётся строками «+0».
     *
     * Отрицательный итог — не «ноль бонусов», а ошибка вызывающего (CHECK
     * `ck_orders_amounts` такого заказа не пропустит), поэтому здесь исключение,
     * а не тихий ноль: молчание спрятало бы её до сверки.
     */
    public static function accrualFor(Money $paid): Money
    {
        if ($paid->isNegative()) {
            throw new DomainRuleViolation(
                sprintf(
                    'A paid order cannot have a negative total (%d %s); bonus accrual is undefined for it.',
                    $paid->minorUnits(),
                    $paid->currency()
                ),
                'INVALID_ACCRUAL'
            );
        }

        return $paid->percentage(self::ACCRUAL_PERCENT);
    }

    /**
     * Сколько бонусов можно списать в заказе с таким subtotal при таком балансе.
     *
     * Два ограничения, и оба обязательны: баланс (списывать больше, чем есть, —
     * это подарок за счёт организатора) и доля от subtotal (иначе заказ можно
     * закрыть целиком бонусами, а бонусы — это скидка, а не второй способ
     * платить). Итог — меньшее из двух.
     *
     * Возвращается `Money`, а не число: результат идёт в `orders.bonus_amount` и
     * в расчёт итога, где валюта обязана совпадать.
     */
    public static function maxSpendable(Money $subtotal, Money $balance): Money
    {
        if ($balance->isNegative()) {
            // Баланс не уходит в минус по CHECK, но защищаться от этого здесь
            // дешевле, чем объяснять отрицательное списание в разборе.
            return Money::zero($subtotal->currency());
        }

        $cap = $subtotal->percentage(self::SPEND_CAP_PERCENT);

        return $cap->greaterThan($balance) ? $balance : $cap;
    }

    /**
     * Когда сгорают бонусы, начисленные в этот момент.
     *
     * Ровно `LIFETIME_MONTHS` месяцев, а не «365 дней»: срок жизни бонусов —
     * календарный, и начисление 1 марта должно сгорать 1 марта, а не 28 февраля
     * (365 дней) и не 2 марта (366). Арифметику месяцев делает PHP.
     *
     * ЕДИНСТВЕННЫЙ НЕОДНОЗНАЧНЫЙ ДЕНЬ — 29 ФЕВРАЛЯ
     *   Через 12 месяцев его не существует (2028-02-29 → 2029 не високосный), и
     *   PHP переносит дату на 1 марта. Это зафиксировано тестом, а не оставлено
     *   на удачу: выбрать можно было 28 февраля или 1 марта, и выбран день
     *   БОЛЬШЕ — для клуба ошибка в сторону «бонус пожил на сутки дольше»
     *   безопаснее обратной, потому что не отнимает у покупателя то, что он уже
     *   видит на счёте.
     */
    public static function expiresAt(DateTimeImmutable $accruedAt): DateTimeImmutable
    {
        return $accruedAt->modify('+' . self::LIFETIME_MONTHS . ' months');
    }

    /**
     * Баланс в бонусах — то число, которое видит покупатель.
     *
     * Округление вниз намеренно: 199 минорных единиц — это 1 бонус и 99 копеек,
     * и показать «2 бонуса» значило бы пообещать больше, чем есть на счёте.
     */
    public static function displayUnits(int $minorUnits): int
    {
        return intdiv($minorUnits, self::MINOR_UNITS_PER_BONUS);
    }

    /** Обратный перевод: сколько минорных единиц в N бонусах. */
    public static function minorUnitsFor(int $bonuses): int
    {
        return $bonuses * self::MINOR_UNITS_PER_BONUS;
    }
}
