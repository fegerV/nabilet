<?php

declare(strict_types=1);

namespace Nabilet\Modules\Events\Http\Requests\Concerns;

/**
 * Словарь отказов формы мероприятия: одно место на Store и Update.
 *
 * ЗАЧЕМ. Массив `messages()` стоял в `StoreEventRequest` и `UpdateEventRequest`
 * побайтово одинаково — те же четыре сообщения для тех же четырёх правил. Рядом
 * тем же дублем стояло и правило `poster_file`: `mimes:jpg,jpeg,png,webp` и
 * `max:5120` в обоих файлах.
 *
 * ПОЧЕМУ ЭТО НЕ БЕЗОБИДНО, ХОТЯ И НЕ ПАДАЕТ. Сообщение и правило — это ПАРА:
 * `max:5120` объясняется словами «не должен превышать 5 МБ». Пока они копии,
 * правка одного молча расходится со вторым. Поднять потолок до 10 МБ, не тронув
 * текст, — и форма начнёт врать пользователю: отклонять файл, который «по
 * правилам» должен был пройти. Ни один тест этого не заметит, потому что тест
 * проверяет поведение валидатора, а не согласованность текста с ним.
 *
 * Поэтому потолок и список форматов объявлены здесь константами, и правило
 * собирается из них же (`posterRule()`), а текст — из константы
 * (`POSTER_MAX_KB`). Одно число на оба файла.
 *
 * Отдельный трейт, а не метод в `HandlesPosterUpload`: тот про СОХРАНЕНИЕ файла,
 * а этот про то, что мы принимаем и как объясняем отказ. Смешав их, трейт
 * перестал бы отвечать на один вопрос.
 *
 * @see HandlesPosterUpload — сохранение афиши, общее для обоих запросов
 */
trait EventFormMessages
{
    /**
     * Потолок афиши в килобайтах: 5 МБ.
     *
     * Объявлен здесь, а не в правиле строкой, чтобы текст сообщения брал число
     * отсюда же. 1024 — килобайт в «МБ», каким его показывает Laravel
     * (`max` в правилах валидации измеряется в килобайтах).
     */
    public const POSTER_MAX_KB = 5120;

    /** Форматы афиши. Тот же список, что в правиле `mimes:` — одна строка на оба. */
    public const POSTER_MIMES = 'jpg,jpeg,png,webp';

    /**
     * Правило для `poster_file`, собранное из тех же констант, что и сообщения.
     *
     * @return list<string>
     */
    protected function posterRule(): array
    {
        return ['nullable', 'file', 'image', 'mimes:' . self::POSTER_MIMES, 'max:' . self::POSTER_MAX_KB];
    }

    /**
     * Сообщения формы мероприятия.
     *
     * `slug.unique` объясняет, ЗАЧЕМ важен адрес: он входит в публичную ссылку,
     * и занятый slug — это не придирка, а невозможность открыть страницу.
     *
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'slug.unique' => 'Такой адрес мероприятия уже занят. Укажите другой — '
                . 'он входит в публичную ссылку на страницу.',
            'poster_file.image' => 'Файл афиши должен быть изображением.',
            'poster_file.mimes' => 'Файл афиши должен быть в формате jpg, png или webp.',
            // Число берётся из константы правила: текст и потолок не могут разойтись.
            'poster_file.max' => sprintf(
                'Файл афиши не должен превышать %d МБ.',
                intdiv(self::POSTER_MAX_KB, 1024),
            ),
        ];
    }
}
