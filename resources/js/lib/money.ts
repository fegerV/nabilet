/**
 * Рубли ↔ копейки — одно правило и один владелец.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ `format.ts`
 *   `format.ts` отвечает на вопрос «как ЧЕЛОВЕКУ показать сумму» и возвращает
 *   готовую строку с пробелами и знаком рубля. Здесь — вопрос «сколько это в
 *   другой единице»: результат остаётся числом, потому что его кладут в поле
 *   ввода, в payload и в счётчик метрики. Смешать их значило бы заставить поле
 *   ввода разбирать обратно то, что форматтер только что собрал.
 *
 * ПОЧЕМУ ЭТО ВООБЩЕ ВОЗНИКЛО
 *   Деньги в проекте — целые minor units (ТЗ §3), но вводит и правит их человек
 *   в рублях. Конверсия стояла в четырнадцати местах шестью написаниями
 *   (`x / 100`, `Math.round(x) / 100`, `Math.round(x / 100)`, `String(x / 100)`,
 *   `x * 100`, `Math.round(x * 100)`), и одно из них поделило на 100 ДВАЖДЫ:
 *   поле «Цена всех выбранных, ₽» в редакторе зала показывало цену места в 100
 *   раз меньше — место за 1500 ₽ выглядело как 15 ₽. Ошибку не было видно, пока
 *   рядом стояла такая же строка без ошибки: переменная называлась
 *   `groupSeatPriceRub`, то есть уже в рублях, а шаблон обращался с ней как с
 *   копейками.
 *
 *   Поэтому единица измерения теперь в ИМЕНИ: `minorToRub`, `rubToMinor`,
 *   `MINOR_PER_RUBLE`. Числа с неоднозначным именем (`price`, `amount`) в этом
 *   модуле не появляются.
 *
 * ДВЕ ПОЛИТИКИ ОБРАТНОЙ КОНВЕРСИИ — ЭТО НЕ РАЗНЫЕ ПРАВИЛА, А РАЗНЫЕ ГРАНИЦЫ
 *   Цена сетки зала не может быть нулевой: сервер (`HallService::
 *   validateSchemaPayload`) отвергает ноль, поэтому `rubToMinor(0)` — отказ, а
 *   положительное значение меньше копейки поднимается до 1 копейки (иначе
 *   «на экране 0, автосохранение падает»). Цена ряда сеанса ноль РАЗРЕШАЕТ —
 *   это бесплатный ряд, и он легален. Разница передаётся параметром
 *   `allowZero`, а не второй копией умножения на 100.
 */

/** Сколько копеек в рубле. Единственная запись этого числа во фронтенде. */
export const MINOR_PER_RUBLE = 100

/**
 * Копейки → рубли. ТОЧНО, без округления: округление — решение того, кто
 * показывает число (целые рубли в поле ввода, `maximumFractionDigits: 0` в
 * `money()`), и принимать его здесь значило бы терять копейки до того, как
 * вызывающий решил, нужны они ему или нет.
 */
export function minorToRub(minor: number): number {
  return minor / MINOR_PER_RUBLE
}

/**
 * Рубли → копейки. `null` — значение негодное и в модель попадать не должно.
 *
 * Принимает строку, потому что источник — поле ввода: `Number('')` даёт 0,
 * а десятичный разделитель в русской раскладке бывает запятой, и `Number`
 * на `'1250,50'` возвращает `NaN` без всякой подсказки.
 *
 * @param opts.allowZero ноль — допустимая цена (бесплатный ряд), а не отказ
 */
export function rubToMinor(value: unknown, opts: { allowZero?: boolean } = {}): number | null {
  const n = Number(String(value).replace(',', '.'))

  if (!Number.isFinite(n) || n < 0) return null
  if (n === 0) return opts.allowZero === true ? 0 : null

  // Положительное, но меньше копейки, — это 1 копейка, а не ноль: записанный
  // ноль разошёлся бы с серверной валидацией.
  return Math.max(1, Math.round(n * MINOR_PER_RUBLE))
}
