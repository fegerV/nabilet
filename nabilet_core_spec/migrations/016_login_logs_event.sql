-- 016: `login_logs.event` — различие входа и выхода по схеме, а не по отсутствию поля.
--
-- ЗАЧЕМ ЭТОТ ФАЙЛ
--   `login_logs` писался ровно из одного места — `SessionIssuer::auditLogout()`,
--   то есть выходом. Строку входа от строки выхода можно было отличить только
--   косвенно: у входа `failure_code` заполнен, у выхода — NULL. Но это верно
--   лишь пока в таблице нет успешного входа: любой будущий писатель, который
--   начнёт писать вход с `failure_code = NULL`, сделает два события
--   неразличимыми. На колонку события ссылался `docs/REVIEW-spec-bundle.md`
--   §3.25 — «у таблицы нет колонки события».
--
-- ЗНАЧЕНИЯ НЕ ВЫДУМАНЫ
--   `login`, `logout`, `login_failed` — это те три события, которые уже
--   различает домен: вход (`SessionIssuer::issue`), выход (`::revoke`) и
--   отказ (`AuthError('bad_credentials')`). Колонка лишь даёт им хранение.
--   CHECK заперещает четвёртое: строка без разбора событий — это строка,
--   которую никто не сможет прочитать.
--
-- ПОЧЕМУ НОВЫЙ ФАЙЛ, А НЕ ПРАВКА 001
--   `001_identity.sql` уже прошёл на развёрнутых базах; добавленная там колонка
--   существовала бы в пакете и нигде больше. Новый сплит плюс зеркало
--   `2026_10_12_000400_add_login_logs_event.php` достают и существующие, и
--   свежие установки — по той же причине, по которой существуют 011, 013, 014, 015.

ALTER TABLE login_logs
  ADD COLUMN event VARCHAR(32) NOT NULL DEFAULT 'login' AFTER success;

ALTER TABLE login_logs
  ADD CONSTRAINT ck_login_logs_event CHECK (event IN ('login','logout','login_failed'));

SET FOREIGN_KEY_CHECKS = 1;
