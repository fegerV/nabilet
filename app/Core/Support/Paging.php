<?php

declare(strict_types=1);

namespace Nabilet\Core\Support;

/**
 * Единственная точка приведения размера страницы к допустимому диапазону.
 *
 * ЗАЧЕМ ПОЯВИЛСЯ. Та же формула была размазана по 13 контроллерам, и к моменту
 * находки уже в двух порядках аргументов: `min(100, max(1, (int) …))` и
 * `max(1, min(100, (int) …))`. Оба дают одинаковый результат, пока вход в
 * диапазоне, — поэтому расхождение молчало. Но «копия, которая разошлась, но
 * пока работает» — это тот же дефект, что и сломанная копия: стоит кому-то
 * перепутать порядок (например, `min(1, max(100, …))`), и запрос перестаёт
 * ограничиваться, а тест на этот контроллер ничего не проверяет. Помимо
 * порядка разошлись и числа: без клампа `?per_page=1000000` клал сервер одним
 * безобидным на вид запросом (прямо об этом написано в `MediaController`).
 *
 * ПОЧЕМУ ВЛАДЕЛЕЦ ПРИНИМАЕТ ДЕФОЛТ И ПОТОЛОК ПАРАМЕТРАМИ, А НЕ ПРЯЧЕТ ИХ.
 * Они подобраны под ресурс и не сводятся к одной константе: медиа — 24
 * (сетка 4×6), админка чекина — 50, отчёт сканов — 200. Свести их в одну
 * «каноническую» пару означало бы изменить поведение списков, то есть принять
 * решение о продукте, а не устранить дефект. Поэтому формула — одна, а числа —
 * у каждого вызывающего свои.
 *
 * ПОЧЕМУ КЛАСС, А НЕ ТРЕЙТ/ФУНКЦИЯ. Он живёт в `app/Core/Support` рядом с
 * `PublicationStatus` и `LikePattern`: чистый, без illuminate, и `verify-purity`
 * это проверяет. Тесты на формулу — `tests/Unit/PagingTest.php`.
 */
final class Paging
{
    /**
     * Привести запрошенный размер страницы к [1, $max]; если входа нет — $default.
     *
     * Канонический порядок — сначала потолок, потом пол: `max(1, min($max, …))`.
     * Любой другой порядок аргументов даёт тот же результат только по совпадению,
     * поэтому все вызовы идут через этот метод, а не прямой `min/max` в контроллере.
     */
    public static function limit(?int $requested, int $default, int $max): int
    {
        $value = $requested ?? $default;

        return max(1, min($max, $value));
    }
}
