namespace Nabilet\Core\Http;

/**
 * Палитра бренда для серверных HTML-документов (аудит P-12/P-16).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ КЛАСС. Серверных документов теперь два: страница 404/410
 * (`NotFoundPage`) и посадочные страницы города/площадки/категории
 * (`LandingPageRenderer`). Оба не подключают CSS приложения — они обязаны
 * отдаваться корректно, когда `dist/` не собран, — поэтому цвета выписаны в них
 * явно. Две копии палитры разошлись бы при первой же правке бренда, и разошлись
 * бы незаметно: 404 и посадочная страница встречаются редко, а выпавший из
 * палитры документ выглядит «чужим сайтом» именно там, где это заметнее всего.
 *
 * ЗНАЧЕНИЯ — из `resources/css/app.css`, блок `.dark` (витрина работает в
 * тёмной теме: `dist/index.html` объявляет `<html class="dark">`). Хранятся как
 * HEX, а не как «R G B»: документы не используют CSS-переменные Tailwind, и
 * подстановка `rgb(var(--x) / .4)` здесь была бы невозможна.
 */
final class BrandPalette
{
    /** `--canvas` — фон страницы. */
    public const CANVAS = '#0B0918';

    /** `--surface` — карточка на фоне. */
    public const SURFACE = '#171331';

    /** `--surface-3` — приподнятая поверхность (строки списка). */
    public const SURFACE_RAISED = '#1D1840';

    /** `--line` — границы. */
    public const LINE = '#2A2450';

    /** `--content` — основной текст. */
    public const CONTENT = '#F4F2FF';

    /** `--content-muted` — вторичный текст. */
    public const MUTED = '#A49DBF';

    /** `--brand-500` — начало бренд-градиента. */
    public const BRAND = '#6D4AFF';

    /** `--accent-500` — конец бренд-градиента. */
    public const ACCENT = '#FF5C22';
}
