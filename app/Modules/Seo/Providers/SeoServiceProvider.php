<?php

declare(strict_types=1);

namespace Nabilet\Modules\Seo\Providers;

use Illuminate\Support\ServiceProvider;

/**
 * SEO module service provider (ТЗ §38).
 *
 * РОУТЫ ЗДЕСЬ НЕ ГРУЗЯТСЯ — и это не упущение.
 *
 * Маршруты модуля подключаются централизованно, но теперь ИЗ `routes/web.php`:
 * `app/Modules/Seo/routes/web.php` содержит и карты сайта (`/sitemap.xml`,
 * аудит P-10a), и посадочные страницы (`/city/*`, `/venue/*`, …). Файла
 * `routes/api.php` у модуля больше нет: карты переехали в корень, потому что
 * `robots.txt` запрещает `/api/v1/` целиком и не должен в следующей строке
 * объявлять оттуда карту сайта.
 *
 * ПОЧЕМУ `loadRoutesFrom()` ЗДЕСЬ ПО-ПРЕЖНЕМУ ЗАПРЕЩЁН. Гейт
 * `tools/verify-route-ownership.php` требует, чтобы у таблицы маршрутов был
 * один владелец. `loadRoutesFrom()` — это голый `require` без группы и без
 * префикса, то есть вторая копия каждого маршрута в корне. Laravel ключует
 * коллекцию по method+uri, поэтому дубль не лежит мёртвым: он перезаписывает
 * первый по имени, и `route()` начинает возвращать адрес, которого нет в
 * контракте.
 *
 * Раньше здесь стоял `boot()` с `loadRoutesFrom()`. Он не стрелял только
 * потому, что `SeoServiceProvider` не перечислен ни в `bootstrap/providers.php`,
 * ни среди бутящихся провайдеров `config/nabilet.php`. То есть баг был не
 * исправлен, а спрятан: первый же, кто добавил бы провайдер в реестр — а это
 * логичный шаг при нормализации провайдеров — получил бы дубли маршрутов
 * сразу для всех адресов модуля. Сейчас это ловит гейт, но правило то же.
 *
 * ЕСЛИ ПОНАДОБИТСЯ ЧТО-ТО ЗАРЕГИСТРИРОВАТЬ (сервис, биндинг, view-неймспейс):
 * добавляйте это в `register()`, но не переносите сюда загрузку роутов.
 * Правильное место для новых маршрутов модуля — `routes/web.php` модуля,
 * подключаемый централизованно из корневого `routes/web.php` ВЫШЕ
 * `Route::fallback()`.
 */
class SeoServiceProvider extends ServiceProvider
{
    public function register(): void
    {
        // Биндингов SEO-сервисам не нужно: `SitemapService`,
        // `StructuredDataService` и `EventCanonicalUrl` разрешаются контейнером
        // автоматически, включая их собственные зависимости.
        //
        // ЗДЕСЬ РАНЬШЕ БЫЛО «не имеют зависимостей» — так было до того, как
        // проверка `canonical_url` на чужой домен переехала из контроллера в
        // `EventCanonicalUrl`. Теперь оба сервиса получают его через конструктор,
        // и авторасширение контейнера закрывает это без единой строчки здесь.
        // Формулировку меняем вместе с фактом: комментарий «зависимостей нет» —
        // это приглашение не посмотреть в конструктор при отладке.
    }
}
