<?php

declare(strict_types=1);

namespace Nabilet\Modules\Matrix\Domain;

use Nabilet\Core\Support\Text;

/**
 * Текстовое сообщение Matrix и его полезная нагрузка.
 *
 * ПОЧЕМУ СООБЩЕНИЕ — ПРОСТОЙ ТЕКСТ
 *   Matrix поддерживает HTML (`format: org.matrix.custom.html`), но HTML обязан
 *   быть ограничен allow-list'ом тегов, иначе Element X покажет разметку как
 *   есть, а не как форматирование. Здесь отправляется `m.text`: содержимое
 *   приходит из данных заказа (номер, сумма, название мероприятия), то есть
 *   частично из пользовательского ввода, и превращать его в разметку значило бы
 *   открыть дверь для инъекции в чужой клиент. Простой текст — безопасный
 *   минимум, и он же ровно то, что нужно административному каналу.
 *
 * ПОЧЕМУ ВЫРЕЗАЮТСЯ УПРАВЛЯЮЩИЕ СИМВОЛЫ
 *   В тело попадают строки из БД (название мероприятия, имя покупателя).
 *   Управляющие символы (кроме `\n` и `\t`) Element X отрисует как «квадратики»,
 *   а `\r` без `\n` ломает переносы. Чистка здесь, на выходе, а не при
 *   сохранении: чужие данные портить нельзя, испортить нужно только то, что
 *   уходит в мессенджер.
 *
 * ОГРАНИЧЕНИЕ ДЛИНЫ
 *   Сообщение формируется из данных заказа и короткое, но потолок нужен: без
 *   него аномально длинное поле ушло бы целиком. Усечение — по символам UTF-8,
 *   а не по байтам, иначе русский текст рвался бы посередине символа.
 *
 * Класс фреймворк-фри (см. `tools/verify-purity.php`).
 */
final class MatrixMessage
{
    /** Потолок тела сообщения в символах UTF-8. */
    public const MAX_BODY_LENGTH = 4000;

    /** Что показывается, если после чистки не осталось ничего осмысленного. */
    public const EMPTY_BODY = '(пустое сообщение)';

    /**
     * Полезная нагрузка события `m.room.message`.
     *
     * @return array{msgtype: string, body: string}
     */
    public static function payload(string $body): array
    {
        return [
            'msgtype' => 'm.text',
            'body' => self::sanitize($body),
        ];
    }

    /**
     * Привести тело к виду, который безопасно и читаемо уходит в Synapse.
     *
     * `preg_replace` без флага `u` намеренно: с ним невалидная UTF-8-строка
     * (а она может прийти из БД) дала бы `null` на всём выражении, и сообщение
     * обнулилось бы целиком. Байтовый класс символов такой строке не вредит.
     */
    public static function sanitize(string $body): string
    {
        $clean = Text::stripControlChars($body, false);

        // Сначала CRLF → LF, потом одиночные CR: иначе первый шаг оставил бы
        // голые `\r` от старого Mac-стиля переводов.
        $clean = str_replace("\r\n", "\n", $clean);
        $clean = str_replace("\r", "\n", $clean);
        $clean = trim($clean);

        if ($clean === '') {
            return self::EMPTY_BODY;
        }

        if (mb_strlen($clean, 'UTF-8') > self::MAX_BODY_LENGTH) {
            $clean = mb_substr($clean, 0, self::MAX_BODY_LENGTH - 1, 'UTF-8') . '…';
        }

        return $clean;
    }
}
