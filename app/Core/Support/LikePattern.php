<?php

declare(strict_types=1);

namespace Nabilet\Core\Support;

/**
 * Экранирование пользовательского ввода для SQL-фильтров `LIKE`.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ КЛАСС. В проекте три `LIKE`-фильтра, и до появления этого
 * хелпера экранирование было ровно в одном из них:
 *
 *   - `OrderRepository`  — `addcslashes($v, '%_\\')` (единственный корректный);
 *   - `UserRepository::search()` — `"%{$query}%"` вообще без экранирования;
 *   - `VenueController::index()` — `'%' . $filters['city'] . '%'` без экранирования.
 *
 * SQL-инъекции здесь не было ни в одном случае (значения биндятся через PDO), но
 * `%` и `_` — это СИМВОЛЫ ШАБЛОНА, а не данные. Поиск по «a_b» без экранирования
 * совпадает с «aXb», а фильтр по «%» превращается в «выбрать всю таблицу» — то
 * есть пользователь управляет формой запроса. Это не теоретическая мелочь:
 * `city=%` на публичном каталоге заставляет MySQL читать все строки вместо
 * индекса, и такой запрос дёшево повторять.
 *
 * ПОЧЕМУ `ESCAPE` УКАЗЫВАЕТСЯ ЯВНО. `addcslashes` экранирует символы, но не
 * говорит СУБД, какой символ считать экранирующим. По умолчанию в MySQL это `\`,
 * и «работает, пока не переключат режим»: при `NO_BACKSLASH_ESCAPES` (реальная
 * настройка, которую ставят на managed-хостингах) обратный слэш перестаёт быть
 * escape-символом, и `\%` снова начинает означать «любые символы». Явная клауза
 * `ESCAPE` убирает эту зависимость от серверного режима.
 *
 * Класс намеренно чистый: только строковые операции, ни одного вызова фреймворка.
 * `app/Core/Support` обязан загружаться и работать без `vendor/` — это проверяет
 * `tools/verify-purity.php`, и импорт `Illuminate\...` здесь сломал бы гейт.
 *
 * @see docs/CODE-QUALITY-GUIDE.md — «Support»
 */
final class LikePattern
{
    /**
     * Символ экранирования. Должен совпадать с тем, что подставляется в
     * `ESCAPE` в {@see expression()} — иначе экранирование не сработает молча.
     */
    public const ESCAPE_CHARACTER = '\\';

    /**
     * Шаблон «содержит подстроку»: `%значение%`.
     *
     * Это то, что нужно подавляющему большинству фильтров (поиск по имени,
     * городу, e-mail).
     */
    public static function contains(string $value): string
    {
        return '%'.self::escape($value).'%';
    }

    /**
     * Шаблон «начинается с»: `значение%`.
     *
     * Полезен там, где нужен индекс: `LIKE 'abc%'` использует B-tree, а
     * `LIKE '%abc%'` — нет.
     */
    public static function startsWith(string $value): string
    {
        return self::escape($value).'%';
    }

    /**
     * Нейтрализовать символы шаблона в пользовательском значении.
     *
     * Порядок замены КРИТИЧЕН: обратный слэш экранируется ПЕРВЫМ. Если сделать
     * это последним, он заэкранирует слэши, только что добавленные перед `%` и
     * `_`, и вместо `\%` в запрос уйдёт `\\%` — то есть «литеральный слэш, затем
     * шаблон». Это классическая ошибка двойного экранирования, и она даёт не
     * ошибку, а тихо неверную выдачу.
     *
     * `str_replace` с массивами делает замены за один проход, поэтому результат
     * детерминирован и не зависит от того, что уже было в строке.
     */
    public static function escape(string $value): string
    {
        return str_replace(
            [self::ESCAPE_CHARACTER, '%', '_'],
            [self::ESCAPE_CHARACTER.self::ESCAPE_CHARACTER, self::ESCAPE_CHARACTER.'%', self::ESCAPE_CHARACTER.'_'],
            $value
        );
    }

    /**
     * SQL-фрагмент для `whereRaw()`: `колонка LIKE ? ESCAPE '\'`.
     *
     * Значение подставляется ВТОРЫМ аргументом `whereRaw()` как binding, никогда
     * не склеивается в строку. Имя колонки приходит из кода, а не из запроса, —
     * но и оно не интерполируется вслепую: см. докблок `assertIdentifier()`.
     *
     * @param string $column Имя колонки (или `таблица.колонка`).
     */
    public static function expression(string $column): string
    {
        self::assertIdentifier($column);

        // `'\\\\'` в одинарных кавычках PHP — это два символа `\\`, которые
        // MySQL разбирает как ОДИН обратный слэш. Ровно он и объявлен
        // ESCAPE_CHARACTER выше.
        return $column." LIKE ? ESCAPE '\\\\'";
    }

    /**
     * Имя колонки в `expression()` подставляется в SQL строкой, поэтому оно
     * обязано быть идентификатором, а не произвольным текстом.
     *
     * Проверка не защищает от внешнего ввода — все вызовы статические и
     * литеральные. Она защищает от БУДУЩЕГО рефакторинга, в котором имя колонки
     * однажды приедет из конфигурации или из запроса: тогда это станет настоящей
     * инъекцией, а `LIKE` — не то место, где её хочется обнаружить.
     */
    private static function assertIdentifier(string $column): void
    {
        if (preg_match('/^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)?$/', $column) !== 1) {
            throw new \InvalidArgumentException(
                sprintf('Ожидалось имя колонки вида `table.column`, получено "%s".', $column)
            );
        }
    }

    private function __construct()
    {
    }
}
