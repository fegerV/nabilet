 *   поэтому его просто перестали запускать.
 *
 * ЗАЧЕМ `spec_ddl_tables()`
 *   Константа может отстать от спеки молча. Функция считает `CREATE TABLE` в
 *   бандле напрямую — величина, не зависящая ни от одного из трёх парсеров.
 *   Расхождение константы с ней падает с внятным сообщением («в бандле 88
