<?php

declare(strict_types=1);

namespace Nabilet\Modules\Loyalty\Domain;

/**
 * Правила награды за приглашение.
 *
 * ЗАЧЕМ ЖЁСТКИЙ ПОТОЛОК
 *   Суммы наград правятся в админке (`LoyaltySettingsService`, scope
 *   `loyalty`), и опечатка в поле «+300» на два нуля — это ₽30 000 за
 *   приглашение. Потолок здесь — последняя линия обороны, а не замена
 *   валидации: валидация объясняет ошибку администратору, а потолок
 *   гарантирует, что через сервис (команда пересчёта, сид, миграция
 *   настроек) всё равно не пройдёт заведомо безумная сумма.
 *
 * ПОЧЕМУ ОТРИЦАТЕЛЬНАЯ СУММА — НОЛЬ, А НЕ ОШИБКА
 *   Отрицательная награда означала бы «списать бонусы за приглашённого друга»
 *   — операции, которой в продукте нет. Молчаливое приведение к нулю
 *   безопаснее отказа: настройка в базе может прийти из сида или миграции, и
 *   падать на оплате заказа из-за неё — значит ломать покупку покупателя
 *   из-за опечатки администратора.
 */
final class ReferralPolicy
{
    /** ₽10 000 в минорных единицах: предел ручной настройки награды. */
    public const MAX_BONUS = 1_000_000;

    /**
     * Награда по настройкам. Суммы обрезаются в [0, MAX_BONUS] — см. заголовок.
     */
    public static function reward(bool $enabled, int $inviterAmount, int $invitedAmount): ReferralReward
    {
        return new ReferralReward(
            $enabled,
            self::normalize($inviterAmount),
            self::normalize($invitedAmount),
        );
    }

    /**
     * Привести сумму награды к [0, MAX_BONUS] — ЕДИНСТВЕННЫЙ владелец этого диапазона.
     *
     * ЗАЧЕМ ПУБЛИЧНЫЙ. Раньше `max(0, …)` был скопирован в `LoyaltySettingsService`
     * четырежды (чтение формы и запись, по обеим сторонам рефералки), причём БЕЗ
     * потолка — то есть это была обрезанная копия правила, которое здесь уже было.
     * Граница HTTP и так отклоняет выход за `MAX_BONUS` (422), но прямой вызов
     * сервиса (сид, миграция, команда) потолок не проверял. Теперь обе стороны
     * зовут один метод: пол в нуле и потолок в `MAX_BONUS` — в одном месте.
     */
    public static function normalize(int $amount): int
    {
        return max(0, min(self::MAX_BONUS, $amount));
    }
}
