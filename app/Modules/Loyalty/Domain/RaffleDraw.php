<?php

declare(strict_types=1);

namespace Nabilet\Modules\Loyalty\Domain;

/**
 * Тираж: распределение билетов по призовым местам.
 *
 * ЗАЧЕМ ЧИСТОЕ РЕШЕНИЕ
 *   Тираж — единственная операция фазы 5, у которой есть СЛУЧАЙНОСТЬ, и
 *   единственная, которую организатор перепроверить не может («а почему
 *   выиграл он?»). Ответ на этот вопрос должен воспроизводиться: алгоритм
 *   живёт фреймворк-фри, принимает источник случайности параметром и
 *   поэтому покрывается юнит-тестами с детерминированным ГПСЧ
 *   (`tests/run.php` не грузит ни базу, ни Eloquent).
 *
 * ПОЧЕМУ БЕЗ ВОЗВРАТА (ОДИН БИЛЕТ — ОДНО МЕСТО)
 *   Билеты тасуются один раз, и места раздаются по очереди: победитель
 *   первого места выбывает из второго. С возвратом один удачливый заказ
 *   забирал бы все призы, если бы мест было больше одного, — и «второе
 *   место досталось тому же человеку» выглядело бы поломкой, а не розыгрышем.
 *   Инвариант держит и схема: `uq_raffle_winners_entry (raffle_id, entry_id)`.
 *
 *   ПОБЕДИТЕЛЬ — ЭТО БИЛЕТ, А НЕ ЧЕЛОВЕК. У человека с двумя заказами два
 *   билета, и он может занять два места: это ровно та же механика, что в
 *   физическом розыгрыше, где у покупателя два купона. Ограничение «один приз
 *   на человека» — продуктовое решение, которого заказчик не просил; когда
 *   попросит, оно станет фильтром ПЕРЕД вызовом `assign()`, а не правкой
 *   алгоритма.
 *
 * ПОЧЕМУ МЕСТА, А НЕ ПОРЯДОК ВЫДАЧИ
 *   Призы нумеруются местами (1, 2, 3), и призовое место — свойство приза
 *   (`raffle_prizes.place`), а не порядок строк в выборке. Поэтому `assign()`
 *   возвращает «место => билет»: ресурс и письмо победителю называют место,
 *   а не позицию в массиве.
 */
final class RaffleDraw
{
    /**
     * Распределить билеты по призовым местам.
     *
     * @param  list<int|string>  $entryIds  все билеты розыгрыша
     * @param  list<int>  $places  призовые места в любом порядке
     * @param  (callable(int): int)|null  $rng  источник случайности (см. выше)
     * @return array<int, int|string>  призовое место => победивший билет
     *
     * Источник случайности по умолчанию — `random_int` (CSPRNG). В тестах
     * подставляется функция с заранее заданной последовательностью: тогда
     * тираж детерминирован и его можно проверить утверждениями.
     */
    public static function assign(array $entryIds, array $places, ?callable $rng = null): array
    {
        $rng ??= static fn (int $bound): int => random_int(0, $bound - 1);

        $orderedPlaces = self::orderedPlaces($places);
        $shuffled = self::shuffle(array_values($entryIds), $rng);

        $winners = [];

        foreach ($orderedPlaces as $index => $place) {
            // $shuffled не короче $orderedPlaces — предусловие проверяет
            // вызывающий (`RaffleService::draw()`), см. `RafflePolicy`.
            $winners[$place] = $shuffled[$index];
        }

        return $winners;
    }

    /**
     * Перемешать список (Фишер—Йетс).
     *
     * Отдельный публичный метод, а не приватная деталь `assign()`: порядок
     * самих билетов — тоже факт розыгрыша (его показывают в отчёте «в каком
     * порядке выпадали»), и его нужно уметь проверить так же детерминированно.
     *
     * @param  list<mixed>  $items
     * @param  (callable(int): int)|null  $rng
     * @return list<mixed>
     */
    public static function shuffle(array $items, ?callable $rng = null): array
    {
        $rng ??= static fn (int $bound): int => random_int(0, $bound - 1);

        $count = count($items);

        for ($i = $count - 1; $i > 0; $i--) {
            $j = $rng($i + 1);

            // Защита от сломанного источника: индекс вне диапазона сделал бы
            // тираж невоспроизводимым молча (PHP берёт null и предупреждает).
            $j = max(0, min($i, $j));

            [$items[$i], $items[$j]] = [$items[$j], $items[$i]];
        }

        return $items;
    }

    /**
     * Места по возрастанию, без дублей.
     *
     * Дубль места («два первых») в данных сделал бы результат неопределённым:
     * `array<int, ...>` ниже просто перезаписал бы запись. Сортировка —
     * потому что призы могли прийти из формы в произвольном порядке, а место
     * 1 получает первого выпавшего билета, а не «тот приз, что в списке выше».
     *
     * @param  list<int>  $places
     * @return list<int>
     */
    private static function orderedPlaces(array $places): array
    {
        $places = array_values(array_unique(array_map('intval', $places)));
        sort($places, \SORT_NUMERIC);

        return $places;
    }
}
