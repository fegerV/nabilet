<?php

declare(strict_types=1);

namespace Nabilet\Modules\Auth\Domain;

/**
 * Параметр `state` OAuth: одноразовое значение, которое связывает НАЧАЛО входа
 * с его ЗАВЕРШЕНИЕМ.
 *
 * ЗАЧЕМ ОН ВООБЩЕ НУЖЕН. Без сверки `state` callback принимает любой валидный
 * `code` от любого браузера — это login CSRF: злоумышленник начинает вход под
 * СВОИМ аккаунтом, забирает `code` из адресной строки (не доводя обмен) и
 * подсовывает ссылку жертве. Жертва открывает её, приложение обменивает код и
 * выдаёт жертве сессию АККАУНТА ЗЛОУМЫШЛЕННИКА — дальше жертва покупает билеты
 * «в чужой кабинет», а злоумышленник ими пользуется. Проверка `state` против
 * значения, которое мы же и выдали этому браузеру, делает чужой `code`
 * бесполезным.
 *
 * ПОЧЕМУ КУКА, А НЕ СЕССИЯ ИЛИ ПОДПИСЬ
 *   Callback приходит от провайдера как обычный переход браузера, то есть с
 *   куками нашего домена и БЕЗ какого-либо заголовка, который поставил бы мы.
 *   Кука — единственный канал, который в этом сценарии доступен и не требует
 *   серверного состояния. Подпись (HMAC) защищала бы от подделки значения, но не
 *   от повторного использования ЧУЖОГО настоящего `state`, а именно это и есть
 *   атака: подписанное значение, выданное злоумышленнику, для него валидно.
 *
 * ПОЧЕМУ `HttpOnly`
 *   Фронту это значение знать не нужно: он не собирает authorize-URL, а идёт на
 *   наш `/auth/{provider}/start`. Значит, куку не должен читать никто, и
 *   скрипт, попавший на страницу, её не прочитает.
 *
 * Чистый класс: только `random_bytes` и `hash_equals` — ни `config()`, ни БД.
 */
final class OAuthState
{
    /** Имя куки. Один владелец — и на запись (`start`), и на проверку (`callback`). */
    public const COOKIE = 'nb_oauth_state';

    /**
     * Сколько живёт начатый вход. Человек должен успеть ввести пароль у
     * провайдера (включая двухфакторный и подтверждение по SMS), но брошенная
     * вкладка не должна оставлять значение бессрочным.
     */
    public const TTL_SECONDS = 900;

    /** Энтропия значения: 32 байта = 256 бит, в hex — 64 символа. */
    public const BYTES = 32;

    /**
     * Новое значение для одного входа.
     *
     * Не `SessionToken::generate()`: у сессионного токена другая судьба (он
     * хешируется и ложится в `user_sessions`), и 512 бит здесь не нужны —
     * значение живёт минуты и не является учётными данными.
     */
    public static function issue(): string
    {
        return bin2hex(random_bytes(self::BYTES));
    }

    /**
     * Совпадает ли `state` из callback с тем, что мы выдали этому браузеру.
     *
     * Сравнение постоянного времени: `state` — не секрет, но сравнение `===`
     * дало бы оракул по времени на подбор, а обходится это одной функцией.
     * `null` с любой стороны — отказ: «куки нет» (вход начат не нами или истёк)
     * и «параметра нет» одинаково означают, что связать начало с завершением
     * нечем.
     */
    public static function matches(?string $issued, ?string $given): bool
    {
        if ($issued === null || $given === null || $issued === '' || $given === '') {
            return false;
        }

        return hash_equals($issued, $given);
    }
}
