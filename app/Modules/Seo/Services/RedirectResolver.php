<?php

declare(strict_types=1);

namespace Nabilet\Modules\Seo\Services;

use Nabilet\Modules\Content\Models\Redirect;

/**
 * Разрешение постоянных редиректов по таблице `redirects` (ТЗ §37).
 *
 * ПОЧЕМУ ЭТО ПОЯВИЛОСЬ. Таблица `redirects` и модель `Redirect` существовали, но
 * потребителя у них не было ни одного: ни middleware, ни контроллера, ни
 * консольной команды. То есть переименование slug, смена раздела или перенос
 * адреса означали безвозвратный 404 — накопленные ссылки и позиции терялись
 * молча. Модуль SEO объявляет менеджер 301/302/307/308 в своём манифесте, так
 * что владелец у этой логики есть.
 *
 * ЧТО ИМЕННО СРАВНИВАЕТСЯ. `redirects.source` — это ПУТЬ (`/event/old-slug`), а
 * не полный URL: домен не хранится, потому что редирект должен переживать смену
 * домена и работать и на стенде, и на проде. Поэтому сравниваем с
 * `Request::getPathInfo()` после нормализации.
 *
 * НОРМАЛИЗАЦИЯ. `/event/old-slug/` и `/event/old-slug` — один и тот же адрес для
 * поисковика, но разные строки для SQL. Приводим к виду «ведущий слэш, без
 * хвостового слэша, без query-строки» с ОБЕИХ сторон — так запись, добавленная
 * вручную в админке, не требует угадывать мелочи оформления.
 *
 * РЕГИСТР НЕ ПОНИЖАЕТСЯ — и это не упущение. Соблазн привести всё к нижнему
 * регистру был, но `publicId` — это ULID в base32 (`01M4KTH5X5X1GW7NRBX18GEJNW`),
 * и понижение регистра в НАЗНАЧЕНИИ даёт адрес, которого не существует: браузер
 * получил бы 301 на `/event/slug/01m4kth…`, а контроллер сверяет `publicId`
 * посимвольно и вернул бы ещё один 301 — то есть лишний переход на каждый заход.
 * Совпадение по источнику при этом остаётся нечувствительным к регистру, потому
 * что таблица объявлена с `utf8mb4_unicode_ci` (см. `nabilet_core_spec/migrations.sql`):
 * `WHERE source = '/Event/Old'` находит `/event/old` на стороне MySQL.
 *
 * ЗАЩИТА ОТ ЦИКЛА. Если `destination` нормализуется в тот же путь, что и
 * `source`, редирект не отдаётся: иначе браузер уходит в ERR_TOO_MANY_REDIRECTS
 * на адресе, который администратор просто опечатал. Одношаговая проверка, а не
 * обход цепочек: цепочки A→B→C спецификацией не запрещены и разрешаются
 * браузером, а вот self-redirect ломает страницу сразу.
 */
class RedirectResolver
{
    /**
     * Коды, которые разрешено отдавать. `redirects.status_code` — SMALLINT без
     * CHECK, поэтому «просто взять значение из БД» означает доверить код ответа
     * администратору, включая `200` или `500`. Здесь остаются только настоящие
     * редиректы; всё остальное считается ошибкой данных и трактуется как 301 —
     * самый безопасный вариант (постоянный, сохраняет метод через 308-семантику
     * только у 307/308, а для публичных страниц метода не существует).
     *
     * @var list<int>
     */
    private const ALLOWED_STATUS_CODES = [301, 302, 307, 308];

    /**
     * Найти активный редирект для пути запроса.
     *
     * @param string $path Путь без query-строки (обычно `Request::getPathInfo()`).
     */
    public function resolve(string $path): ?Redirect
    {
        $normalized = $this->normalize($path);

        if ($normalized === '/') {
            // Корень сайта — это витрина, а не «старый адрес». Редирект на `/`
            // превратил бы главную в бесконечный переход саму на себя.
            return null;
        }

        $redirect = Redirect::query()
            ->where('active', true)
            ->where('source', $normalized)
            ->first();

        if ($redirect === null) {
            return null;
        }

        if ($this->isSelfRedirect($redirect->destination, $normalized)) {
            // Самопереход: запись есть, но она бессмысленна. Отдаём страницу
            // как обычно, а не ломаем её бесконечным редиректом.
            return null;
        }

        return $redirect;
    }

    /**
     * Ведёт ли назначение туда же, куда и источник.
     *
     * Сравнение регистронезависимое — намеренно расходится с `normalize()`.
     * Причина: `source` ищется средствами MySQL с коллацией `utf8mb4_unicode_ci`,
     * то есть запись `/Event/Old` находится по запросу `/event/old`. Если бы
     * проверка самоперехода сравнивала строки побайтово, такая запись прошла бы
     * как «разные адреса» и браузер получил бы цикл. Здесь регистр не несёт
     * смысла, поэтому приводим к нижнему — только для ЭТОГО сравнения.
     */
    private function isSelfRedirect(string $destination, string $source): bool
    {
        return mb_strtolower($this->normalize($destination)) === mb_strtolower($source);
    }

    /**
     * Код ответа из записи, суженный до допустимых редиректов.
     */
    public function statusCode(Redirect $redirect): int
    {
        return in_array($redirect->status_code, self::ALLOWED_STATUS_CODES, true)
            ? $redirect->status_code
            : 301;
    }

    /**
     * Привести путь к канонической форме для сравнения с `redirects.source`.
     *
     * Отдельный публичный метод, а не приватный хелпер: ровно эту же
     * нормализацию обязан применять тот, кто ЗАПИСЫВАЕТ редирект (смена slug в
     * `EventController::update()`). Две копии правила разошлись бы, и запись
     * «/event/old» перестала бы находиться при запросе «/event/old/».
     *
     * Регистр НЕ меняется — см. пояснение в докблоке класса: понижение сломало бы
     * `publicId` в назначении, а нечувствительность к регистру при поиске даёт
     * коллация таблицы.
     */
    public function normalize(string $path): string
    {
        // Отбрасываем query/fragment: они не часть адреса страницы.
        $path = (string) preg_replace('/[?#].*$/', '', $path);

        // Полный URL («https://nabilet.ru/event/x») приводим к пути — иначе
        // запись, скопированная из адресной строки целиком, никогда не совпадёт.
        if (preg_match('#^https?://[^/]+(/.*)?$#i', $path, $m) === 1) {
            $path = $m[1] ?? '/';
        }

        $path = '/'.ltrim(trim($path), '/');

        if ($path !== '/') {
            $path = rtrim($path, '/');
        }

        return $path;
    }
}
