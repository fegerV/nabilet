 * площадки привязываются к организации-владельцу: при установке установщик
 * создаёт её сам (`InstallerController::bootstrapOrganization()`), и сидер
 * берёт ту же самую. Если организаций нет вовсе (сидер запущен на пустой базе
 * до установщика), площадки НЕ создаются — молчаливое создание арендатора
 * опаснее пропуска: некому было бы их администрировать. Явный адресат задаётся
 * ключом `nabilet.seed_venues_organization_id`
 * (`NABILET_SEED_VENUES_ORGANIZATION_ID`).
 *
 * ГОРОД. Улицы Сургута — `city = «Сургут»`; площадки Сургутского района
 * (Белый Яр, Барсово) сохраняют свой населённый пункт, иначе они попадали бы
 * в городскую посадочную страницу Сургута и в разметку `PostalAddress` с
 * неверным `addressLocality`.
 *
 * ТЕКСТЫ. Описания перенесены из афиши площадок без переписывания: это
 * фактический материал (год основания, вместимость, направления), который
 * администратор может править в админке. Упоминания стороннего сервиса продажи
 * билетов из текстов убраны — на этой витрине они были бы рекламой чужой кассы.
 */
