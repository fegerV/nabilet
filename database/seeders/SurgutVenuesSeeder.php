    public const CITY = 'Сургут';

    /** Регион — субъект РФ для `PostalAddress.addressRegion`. */
    public const REGION = 'Ханты-Мансийский автономный округ — Югра';

    /**
     * Код страны ISO 3166-1 alpha-2.
     *
     * `addressCountry` в schema.org ожидает код, а не название; значение по
     * умолчанию в `StructuredDataService::generatePlace()` — тоже `RU`.
     */
    public const COUNTRY = 'RU';

    public function run(): void
    {
        $organizationId = $this->resolveOrganizationId();

        if ($organizationId === null) {
            $message = 'Площадки Сургута не созданы: в базе нет ни одной организации. '
                . 'Сначала выполните установку (или создайте организацию), затем повторите `db:seed`.';

            $this->command?->warn($message);
            echo $message . "\n";

            return;
        }

        // Существующие слаги читаем одним запросом: `venues.slug` уникален
        // глобально, поэтому карта «слаг → id» однозначна.
        $existing = DB::table('venues')->pluck('id', 'slug')->all();

        $created = 0;
        $now = now();

        foreach (self::venues() as $venue) {
            if (isset($existing[$venue['slug']])) {
                continue;
            }

            DB::table('venues')->insert([
                // Конвенция проекта: `public_id` — char(26) ULID, NOT NULL.
                'public_id' => (string) Str::ulid()->toBase32(),
                'organization_id' => $organizationId,
                'name' => $venue['name'],
                'slug' => $venue['slug'],
                'description' => $venue['description'],
                'country' => self::COUNTRY,
                'region' => self::REGION,
                'city' => $venue['city'],
                'address' => $venue['address'],
                'status' => 'active',
                'created_at' => $now,
                'updated_at' => $now,
            ]);

            $created++;
        }

        $this->command?->info(sprintf(
            'Площадки Сургута: создано %d, уже было %d.',
            $created,
            count(self::venues()) - $created,
        ));

        echo sprintf("Surgut venues seeded: %d created, %d already present.\n", $created, count(self::venues()) - $created);
    }

    /**
     * Организация-владелец для стартового каталога.
     *
     * Порядок: явный ключ конфигурации → организация администратора (при
     * установке она ровно одна и создаётся установщиком) → самая первая
     * организация → `null`.
     */
    private function resolveOrganizationId(): ?int
    {
        $configured = config('nabilet.seed_venues_organization_id');

        if ($configured !== null && $configured !== '') {
            $id = DB::table('organizations')->where('id', (int) $configured)->value('id');

            if ($id !== null) {
                return (int) $id;
            }
        }

        $adminOrganization = DB::table('user_organization')
            ->join('roles', 'roles.id', '=', 'user_organization.role_id')
            ->where('roles.slug', 'admin')
            ->orderBy('user_organization.user_id')
            ->value('user_organization.organization_id');

        if ($adminOrganization !== null) {
            return (int) $adminOrganization;
        }

        $first = DB::table('organizations')->orderBy('id')->value('id');

        return $first !== null ? (int) $first : null;
    }

