    public function run(): void
    {
        $now = now();
        foreach ($this->pages() as $slug => $page) {
            $exists = DB::table('pages')->whereNull('organization_id')->where('slug', $slug)->exists();
            if ($exists) {
                continue;
            }

            DB::table('pages')->insert([
                'public_id' => (string) Str::ulid()->toBase32(),
                'organization_id' => null,
                'title' => $page['title'],
                'slug' => $slug,
                'content' => '<div class="article-body">' . $page['content'] . '</div>',
                'status' => 'published',
                'published_at' => $now,
                'created_at' => $now,
                'updated_at' => $now,
            ]);
        }
    }
