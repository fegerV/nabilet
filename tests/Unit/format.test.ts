/**
 * Склонение по-русски — одно правило, один владелец.
 *
 * ПОЧЕМУ ЭТОТ ФАЙЛ ВООБЩЕ ПОЯВИЛСЯ
 *   `plural()` в `lib/format.ts` существовал с самого начала и на витрине
 *   вызывался везде: «3 билета», «5 бонусов», «2 события». А в админке рядом
 *   жили рукописные копии — `n === 1 ? 'мероприятие' : 'мероприятий'`. Копия
 *   верна для 1 и для 5, поэтому и выглядела правильной; для 2, 3 и 4 обзор
 *   писал «2 мероприятий ещё в черновиках», «3 заказов ждут оплаты»,
 *   «2 неудачных платежей». Ни одного теста на `plural()` при этом не было —
 *   ни на фронте, ни на бэке за пределами одной таблицы в `RuTextTest.php`.
 *
 * ЧТО ЗДЕСЬ СТОРОЖИТСЯ
 *   1. Таблица границ 11–14, 21–24, 101–114 — число-в-число как в
 *      `tests/Unit/RuTextTest.php`. Правило живёт на двух языках, и сверка
 *      автоматической быть не может; зато обе таблицы закрепляют ОДИН набор
 *      границ, и правка правила в одном месте не пройдёт молча во втором.
 *   2. Ярлыки (`seatsLabel`, `ticketsLabel`, `rowsLabel`) — не «удобные
 *      обёртки», а единственный способ собрать «N мест»: пока ярлык есть,
 *      склеить строку руками значит скопировать правило.
 *   3. Статический сторож: в `resources/js` нет ни одной подписи, где число
 *      подставлено к существительному в родительном падеже множественного
 *      числа, и ни одного тернарника «1 → слово А, иначе слово Б».
 */
import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { plural, rowsLabel, seatsLabel, ticketsLabel } from '@/lib/format'

describe('plural', () => {
  /**
   * Таблица-близнец `tests/Unit/RuTextTest.php::testPluralKeepsTheRussianRule`.
   *
   * Продублирована намеренно: PHP и TS не могут позвать друг друга, поэтому
   * общего источника у таблиц нет. Что здесь важно — обе закрепляют ОДНИ
   * границы (11–14 — исключение: оканчиваются на 1–4, а склоняются как «11
   * билетов», поэтому решает `% 100`, а не `% 10`). Если правило поменяют в
   * одном языке, вторая таблица об этом не узнает — но расхождение хотя бы
   * будет видно как расхождение двух таблиц, а не как «на фронте 2 билета».
   */
  const TABLE: Array<[number, string]> = [
    // базовые формы и первая граница
    [0, 'билетов'],
    [1, 'билет'],
    [2, 'билета'],
    [3, 'билета'],
    [4, 'билета'],
    [5, 'билетов'],
    [10, 'билетов'],
    // 11–14: оканчиваются на 1–4, но склоняются как 5
    [11, 'билетов'],
    [12, 'билетов'],
    [13, 'билетов'],
    [14, 'билетов'],
    // 21–24: снова по последней цифре
    [21, 'билет'],
    [22, 'билета'],
    [23, 'билета'],
    [24, 'билета'],
    [25, 'билетов'],
    // 101–114: та же граница на третьей сотне
    [101, 'билет'],
    [102, 'билета'],
    [104, 'билета'],
    [111, 'билетов'],
    [112, 'билетов'],
    [114, 'билетов'],
  ]

  it('склоняет по таблице границ', () => {
    for (const [n, expected] of TABLE) {
      expect(plural(n, 'билет', 'билета', 'билетов'), `plural(${n})`).toBe(expected)
    }
  })

  it('подставляет формы в том порядке, в котором их дали', () => {
    // Порядок аргументов — часть контракта: `one, few, many`, как в PHP-двойнике.
    expect(plural(1, 'заказ', 'заказа', 'заказов')).toBe('заказ')
    expect(plural(2, 'заказ', 'заказа', 'заказов')).toBe('заказа')
    expect(plural(7, 'заказ', 'заказа', 'заказов')).toBe('заказов')
  })
})

describe('ярлыки количества', () => {
  it('места', () => {
    expect(seatsLabel(1)).toBe('1 место')
    expect(seatsLabel(2)).toBe('2 места')
    expect(seatsLabel(5)).toBe('5 мест')
    expect(seatsLabel(11)).toBe('11 мест')
    expect(seatsLabel(21)).toBe('21 место')
  })

  it('билеты', () => {
    expect(ticketsLabel(1)).toBe('1 билет')
    expect(ticketsLabel(3)).toBe('3 билета')
    expect(ticketsLabel(12)).toBe('12 билетов')
  })

  it('ряды', () => {
    expect(rowsLabel(1)).toBe('1 ряд')
    expect(rowsLabel(4)).toBe('4 ряда')
    expect(rowsLabel(14)).toBe('14 рядов')
  })

  it('ноль склоняется как «много»', () => {
    // «0 мест», а не «0 место»: витрина показывает пустой зал именно так.
    expect(seatsLabel(0)).toBe('0 мест')
    expect(ticketsLabel(0)).toBe('0 билетов')
  })
})

describe('один владелец склонения', () => {
  /**
   * Число, подставленное к существительному в родительном падеже множественного
   * числа: `${n} мест`, `{{ n }} билетов`.
   *
   * `\b` здесь не работает: в JS он опирается на `\w`, а тот ASCII-only, и
   * после кириллицы границы слова не находит. Поэтому `(?!\p{L})` с флагом `u`.
   * Фигурные скобки экранированы: в режиме `u` одиночная `}` — синтаксическая
   * ошибка («Lone quantifier brackets»), а не литерал.
   */
  const BARE_PLURAL =
    /(?:\$\{[^\}]*\}|\}\})\s*(?:мест|билетов|рядов|заказов|мероприятий|секторов|платежей|платёжей|позиций|бонусов)(?!\p{L})/u

  /**
   * Тернарник «1 → слово А, иначе слово Б» — вторая форма той же копии.
   *
   * Обе ветви — кириллические строковые литералы: `n === 1 ? 'мероприятие' :
   * 'мероприятий'`. Переключение существительного на ЯРЛЫК (`'Место'` против
   * `seatsLabel(n)`) под правило не попадает: там вторая ветвь — вызов
   * владельца, а не вторая форма слова.
   */
  const BINARY_PLURAL = /==\s*1\s*\?\s*'[^']*[А-Яа-яЁё][^']*'\s*:\s*'[^']*[А-Яа-яЁё][^']*'/

  /** Комментарии выбрасываются: сторож не имеет права матчить пояснение. */
  function codeOnly(source: string): string {
    return source
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/\/\/[^\n]*/g, '')
  }

  function sourceFiles(dir: string): string[] {
    const found: string[] = []

    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name)

      if (entry.isDirectory()) {
        found.push(...sourceFiles(full))
        continue
      }

      if (entry.name.endsWith('.ts') || entry.name.endsWith('.vue')) {
        found.push(full)
      }
    }

    return found
  }

  it('нигде не склеивает число с существительным руками', () => {
    // `process.cwd()`, а не `import.meta.url`: под jsdom `fileURLToPath(new
    // URL(...))` падает с «The URL must be of scheme file».
    const root = join(process.cwd(), 'resources', 'js')
    const offenders: string[] = []

    for (const file of sourceFiles(root)) {
      const relative = file.slice(root.length + 1).replace(/\\/g, '/')

      // Сам владелец — единственное место, где существительное стоит рядом с
      // числом: `seatsLabel` и есть `plural(...)`.
      if (relative === 'lib/format.ts') {
        continue
      }

      const lines = codeOnly(readFileSync(file, 'utf8')).split('\n')

      lines.forEach((line, index) => {
        if (BARE_PLURAL.test(line) || BINARY_PLURAL.test(line)) {
          offenders.push(`${relative}:${index + 1}: ${line.trim()}`)
        }
      })
    }

    expect(offenders, offenders.join('\n')).toEqual([])
  })
})
