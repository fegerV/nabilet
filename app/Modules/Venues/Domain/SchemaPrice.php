<?php

declare(strict_types=1);

namespace Nabilet\Modules\Venues\Domain;

/**
 * Действующая цена узла схемы зала — в минорных единицах (копейках).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ КЛАСС. Вопрос «сколько стоит это место» решался в схеме зала
 * в семи местах, и в каждом — своей цепочкой запасных вариантов:
 *
 *   `HallSchemaVersion::toInventoryFormat()` — три раза: стоячая зона, поднятая
 *       из `staticObjects` (с запасным вариантом на цене сектора), цена ряда и
 *       одиночная стоячая зона без сектора;
 *   `HallService::validateSchemaPayload()` — дважды: действующая цена места и
 *       цена продаваемой стоячей зоны;
 *   `InventoryService::generateFromSchema()` — индивидуальная цена места.
 *
 * Цепочки были записаны по-разному и уже разошлись: чтец в БД-формате брал
 * `priceMinor` и падал на легаси `price` через `(int)`, валидатор места вообще
 * не смотрел на индивидуальную цену места, а сторожевые тесты повторяли
 * цепочку ещё двумя своими копиями. Пока копии совпадали, расхождение не
 * проявлялось; оно проявилось бы при первом же изменении приоритета — молча,
 * потому что обе ветки отвечают 200.
 *
 * ЧТО ИМЕННО ЗДЕСЬ ОДНО. Два правила, и только они:
 *
 *   1. ЦЕНА УЗЛА ХРАНИТСЯ ПОД ДВУМЯ ИМЕНАМИ. `priceMinor` — современное поле
 *      редактора, `price` — легаси (сидеры и импорт Афиши). Побеждает
 *      `priceMinor`; `price` читается, чтобы старые схемы продолжали
 *      продаваться, а не превращались в нулевые.
 *   2. ПРИОРИТЕТ ЦЕНЫ. Место → ряд (`rowPrices`) → сектор. Место дороже ряда,
 *      ряд дороже сектора: так это описано в подсказке админки («Приоритет при
 *      продаже: место → ряд → сектор»), и так это должно быть в коде.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Проверки «цена положительна и это целое». Это отдельный
 * вопрос с разными ответами на двух границах: API отвергает некорректную цену
 * (`HallService`), а чтец уже сохранённых данных обязан деградировать
 * (нулевая цена → `isSellable()` = false), но не падать. Поэтому валидность
 * остаётся у вызывающего, а класс отдаёт `?self` и `isSellable()`.
 *
 * ПОЧЕМУ НЕ `Money`. `Money` — про валюту и про арифметику над суммами. В схеме
 * зала цена всегда целые копейки без валюты, и никаких операций, кроме выбора
 * нужного уровня, здесь не происходит: оборачивать `int` в объект с валютой
 * значило бы выдумать валюту, которой в схеме нет. Масштаб (копейки) не
 * меняется — поэтому и пересчёта здесь нет.
 *
 * Чистый класс: без фреймворка, проверяется dependency-free раннером.
 */
final class SchemaPrice
{
    /**
     * Имена поля цены узла схемы, в порядке приоритета.
     *
     * `priceMinor` — редактор (ТЗ §50), `price` — легаси сидеров и импорта.
     * Оба хранят ЦЕЛЫЕ КОПЕЙКИ: это не «рубли в старом поле», а то же самое
     * число под другим именем, поэтому пересчёта масштаба при чтении нет.
     */
    public const NODE_KEYS = ['priceMinor', 'price'];

    /**
     * Верхняя граница разумного: 10^15 копеек. Всё, что длиннее, — не цена, а
     * случайно пойманное значение; `(int)` на нём уже переполнялся бы.
     */
    private const MAX_DIGITS = 15;

    private function __construct(private readonly int $minorUnits)
    {
    }

    /**
     * Цена узла схемы (сектор, стоячая зона) по правилу «`priceMinor`
     * побеждает `price`».
     *
     * Значение `0` — это ОТВЕТ, а не отсутствие ответа: цепочка уровней
     * останавливается на первом объявленном поле, даже если оно нулевое, —
     * иначе нулевая цена сектора молча подменялась бы легаси-полем. Такое
     * значение доедет до вызывающего и будет отвергнуто `isSellable()`.
     */
    public static function ofNode(mixed $node): ?self
    {
        if (!is_array($node)) {
            return null;
        }

        foreach (self::NODE_KEYS as $key) {
            if (!array_key_exists($key, $node)) {
                continue;
            }

            $price = self::parse($node[$key]);

            if ($price !== null) {
                return $price;
            }
        }

        return null;
    }

    /**
     * Цена ряда: `rowPrices[ряд]` перекрывает цену сектора.
     *
     * Ключ ищется и строкой, и числом: `rowPrices` приезжает из JSON-объекта
     * (ключи — строки), но редактор строит его как `Record<number, number>`,
     * и после round-trip через PHP-массив ключи становятся целыми.
     */
    public static function forRow(int|string $rowNo, array $sector): ?self
    {
        $rowPrices = is_array($sector['rowPrices'] ?? null) ? $sector['rowPrices'] : [];

        $declared = $rowPrices[(string) $rowNo] ?? $rowPrices[$rowNo] ?? null;
        $price = self::parse($declared);

        return $price ?? self::ofNode($sector);
    }

    /**
     * Цена продаваемой стоячей зоны: своя цена, затем (если зона поднимается в
     * сектор-обёртку) цена этого сектора.
     *
     * Второй аргумент — именно запасной вариант, а не обязательный: одиночная
     * зона на холсте сектора не имеет и живёт только своей ценой.
     */
    public static function forStandingZone(array $object, ?array $sector = null): ?self
    {
        $price = self::ofNode($object);

        if ($price !== null || $sector === null) {
            return $price;
        }

        return self::ofNode($sector);
    }

    /**
     * Индивидуальная цена места (§54): перекрывает цену ряда, но только если
     * она вообще является ценой.
     *
     * Здесь, в отличие от `ofNode()`, некорректное значение означает НЕ
     * «нулевую цену», а «своей цены нет» — место наследует цену ряда. Иначе
     * место с мусором в `priceMinor` продавалось бы за ноль вместо цены ряда.
     */
    public static function seatOverride(mixed $raw): ?self
    {
        $price = self::parse($raw);

        return $price !== null && $price->isSellable() ? $price : null;
    }

    public function minorUnits(): int
    {
        return $this->minorUnits;
    }

    /**
     * Годится ли цена в продажу: целые копейки, не меньше одной.
     *
     * Ноль и отрицательное — не цена, а незаполненное поле: место с такой
     * ценой стало бы бесплатным лотом в инвентаре.
     */
    public function isSellable(): bool
    {
        return $this->minorUnits >= 1;
    }

    /**
     * Разбор одного значения цены. Терпим к цифровой строке, потому что схема
     * проходит через JSON и обратно, и `"5000"` — та же цена, что `5000`.
     *
     * Вещественное число — отказ, а не округление: деньги в проекте целые
     * (ТЗ §3), и `2999.5` означало бы, что источник прислал не копейки.
     */
    private static function parse(mixed $raw): ?self
    {
        if (is_int($raw)) {
            return new self($raw);
        }

        if (is_string($raw)) {
            $trimmed = trim($raw);

            if (preg_match('/^-?\d{1,' . self::MAX_DIGITS . '}$/', $trimmed) === 1) {
                return new self((int) $trimmed);
            }
        }

        return null;
    }
}
