<?php

declare(strict_types=1);

namespace Nabilet\Modules\Loyalty\Domain;

/**
 * Правило персональных рекомендаций — «что показать покупателю дальше».
 *
 * ФАЙЛ ФРЕЙМВОРК-ФРИ НАМЕРЕННО
 *   Решение «в каком порядке показать мероприятия» — это чистая функция от
 *   двух списков: весов категорий (что покупатель уже любит) и кандидатов
 *   (что вообще можно предложить). Ни базы, ни `Carbon`, ни `Eloquent` здесь
 *   нет — поэтому правило исполняется `php tests/run.php` без `vendor/` и без
 *   MySQL (см. `tools/verify-purity.php`). SQL-часть — «кого взять в
 *   кандидаты» — живёт в `RecommendationService`, а «в каком порядке» —
 *   здесь, ровно как `SalesWindow` отделяет окно продаж от модели `Session`.
 *
 * ПОЧЕМУ ВЕСА, А НЕ ГОЛОЕ МНОЖЕСТВО КАТЕГОРИЙ
 *   Категория, которую покупатель трогал трижды (избранное + подписка +
 *   оплаченный заказ), — более сильный сигнал, чем категория с одной отметкой.
 *   Вес приходит снаружи уже посчитанным (сколько раз категория встретилась в
 *   профиле вкуса), а правило только складывает его с кандидатом. Считать вес
 *   здесь значило бы требовать от правила знания о том, из каких таблиц он
 *   берётся, — и сломало бы фреймворк-фри-чистоту.
 *
 * ГРАНИЦЫ ЛИМИТА — ЧАСТЬ КОНТРАКТА, А НЕ ОФОРМЛЕНИЕ
 *   `limit` приходит из строки запроса, то есть от клиента, и обязан быть
 *   зажат: `0` или отрицательное число дали бы пустой ответ на ровном месте, а
 *   `limit=1000000` — попытку отдать всю афишу одним запросом. Поэтому
 *   `clampLimit()` — единственная точка, где число превращается в допустимое,
 *   и сервис зовёт именно её, а не `min()` руками.
 */
final class RecommendationPolicy
{
    /** Сколько карточек показываем, если клиент не попросил иначе. */
    public const DEFAULT_LIMIT = 8;

    /** Потолок: «Рекомендуем» — полка, а не второй каталог. */
    public const MAX_LIMIT = 24;

    /**
     * Привести запрошенный лимит к допустимому диапазону.
     *
     * Нечисловой или неположительный лимит — это «как по умолчанию», а не
     * ошибка валидации: рекомендации — необязательная витринная полка, и
     * ронять из-за неё страницу не за что. Слишком большой — обрезается
     * потолком, чтобы один запрос не тянул весь каталог.
     */
    public static function clampLimit(int $limit): int
    {
        if ($limit < 1) {
            return self::DEFAULT_LIMIT;
        }

        return min($limit, self::MAX_LIMIT);
    }

    /**
     * Отранжировать кандидатов и вернуть идентификаторы лучших.
     *
     * @param array<int|string, int> $weights   category_id => вес (сколько раз
     *                                          категория встретилась в профиле)
     * @param list<array{event_id:int, category_id:int|null, starts_at_ts:int|null}> $candidates
     *        `starts_at_ts` — метка времени ближайшего предстоящего сеанса в
     *        СЕКУНДАХ (уже нормализованная сервисом в один часовой пояс), а не
     *        строка: сравнивать ISO-строки с разными смещениями лексикографически
     *        нельзя, а `Carbon` в этом файле запрещён.
     * @return list<int> идентификаторы мероприятий в порядке показа
     *
     * КАНДИДАТ БЕЗ СИГНАЛА НЕ ПОПАДАЕТ В ВЫДАЧУ
     *   Вес `0` (категория не из профиля) означает «мы не знаем, что это
     *   покупателю интересно». Показывать такое в «Рекомендуем» — значит
     *   выдавать случайный каталог под видом персональной полки. Такие
     *   кандидаты отсеиваются здесь, а не в SQL, чтобы правило было
     *   самодостаточным: сервис вправе передать лишнее, решение — не показывать.
     */
    public static function rank(array $weights, array $candidates, int $limit): array
    {
        $limit = self::clampLimit($limit);

        if ($limit < 1 || $candidates === []) {
            return [];
        }

        $scored = [];

        foreach ($candidates as $candidate) {
            $categoryId = $candidate['category_id'] ?? null;
            $score = ($categoryId !== null && isset($weights[$categoryId]))
                ? (int) $weights[$categoryId]
                : 0;

            if ($score <= 0) {
                continue;
            }

            $scored[] = [
                'event_id' => (int) $candidate['event_id'],
                'score' => $score,
                'starts_at_ts' => $candidate['starts_at_ts'] ?? null,
            ];
        }

        usort($scored, static function (array $a, array $b): int {
            // 1. Сила сигнала: чем ближе к вкусу, тем выше.
            if ($a['score'] !== $b['score']) {
                return $b['score'] <=> $a['score'];
            }

            // 2. Ближайший сеанс: «что можно посмотреть скоро» выше «когда-нибудь».
            //    Кандидат без даты — в конец, а не в начало: пустая дата не
            //    повод показать его раньше того, что уже на календаре.
            $at = $a['starts_at_ts'];
            $bt = $b['starts_at_ts'];

            if ($at === null && $bt !== null) {
                return 1;
            }
            if ($at !== null && $bt === null) {
                return -1;
            }
            if ($at !== null && $bt !== null && $at !== $bt) {
                return $at <=> $bt;
            }

            // 3. Идентификатор — только ради детерминизма: два кандидата с
            //    равным весом и датой не должны менять порядок от запроса к
            //    запросу (иначе витрина «дрожит» при каждом обновлении).
            return $a['event_id'] <=> $b['event_id'];
        });

        return array_slice(
            array_map(static fn (array $row): int => $row['event_id'], $scored),
            0,
            $limit
        );
    }

    private function __construct()
    {
    }
}
