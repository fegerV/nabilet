 * с чем: событие нельзя создать без зала (`sessions.venue_id` + инвентарь), а
 * зал — без площадки. Пока нет ни одной площадки, администратору нечего выбрать
 * в выпадающем списке ни на шаге создания события, ни на шаге сеанса. Сидер
 * снимает этот первый барьер — каталог заполнен теми площадками, что
 * перечислены в афише Сургута, и владелец сразу заводит залы и события.
 *
 * ПОЧЕМУ ЭТО НЕ ДАЁТ СРАЗУ ГОТОВЫХ ПУБЛИЧНЫХ СТРАНИЦ. Посадочная страница
 * площадки (`/venue/{slug}`) и её запись в `/sitemap-venues.xml` появляются
 * только при наличии публично видимого события: пустая страница отвечает 404
 * (`LandingController`), а адрес в карте, ведущий на 404, — ошибка для Google.
 * То есть каталог из этого сидера «оживает» на витрине сам, без дополнительной
 * настройки, ровно в тот момент, когда в площадке появляется первое событие.
 *
 * ЧТО ИМЕННО КЛАДЁТСЯ. Только строка `venues` — ни залов, ни схем, ни событий.
 * Площадка без зала — рабочее состояние: зал и схему администратор заводит
 * сам, а событие без зала создать нельзя (`sessions.venue_id` + инвентарь).
 * Пустой каталог площадок блокирует вообще всё, поэтому наполняется первым.
 *
 * ИДЕМПОТЕНТНОСТЬ. Ключ — `venues.slug`, уникальный глобально (`uq_venues_slug`,
 * миграция 2026_10_11_000200). Существующая площадка не перезаписывается:
 * администратор вправе править описание и адрес, и повторный `db:seed --force`
 * (его запускает установщик, а также деплой) не должен возвращать чужие правки
 * к исходному тексту. Слаг задан в сидере явно, а не выводится из названия:
 * публичный адрес площадки не должен меняться от правки названия или от смены
 * версии транслитерации в `Str::slug()`.
 *
